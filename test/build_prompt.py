# ★ 这是「后备资源」里唯一能上公开站的一份，因为它**是孔老师自己写的**：
#   教科书 PDF、学科网课件、上好课 PPT 那些有版权，不能往公开的 GitHub Pages 上放
#   （她的原话是"没必要显示在客户面前，只需要成为网站的读取资源"——
#     但网页读不到她本机的 C 盘，能上站的只有她自己创作的部分）。
#   格式跟教材索引一模一样（"### 标题" + 五个【…】标记），所以直接复用同一套二元组 BM25，
#   一个分词器、一个检索器都不用新写。
#   【认这类题】/【还没开口】/【复述完了】/【卡住说不出】/【说对了】正好对上「追问的五个台阶」。
ZHUA_DIR = r"C:\数学办公\宜兴东氿中学\24-知识库\02-条目"
ZHUA_FILES = [("03-七上（试点批）.md", "七上"), ("04-七下.md", "七下"), ("05-八上.md", "八上"),
              ("06-八下.md", "八下"), ("07-九上.md", "九上"), ("08-九下.md", "九下")]
OUT_ZHUA = r"C:\数学办公\数根\js\zhuawen.js"

zparts, zn = [], 0
for fn, vol in ZHUA_FILES:
    raw = io.open(os.path.join(ZHUA_DIR, fn), encoding="utf-8").read().replace("\r\n", "\n")
    # 每条标题前面挂上册别（"### 数轴·三要素｜也叫：…" → "### 七上 · 数轴·三要素｜也叫：…"）
    # 这样模型报位置时能说清是哪一册（教材索引也是这么标的），一个知识点跨册同名也不会撞
    body = re.sub(r"(?m)^###[ \t]+", "### %s · " % vol, raw)
    n = len(re.findall(r"(?m)^###[ \t]", raw))
    zn += n
    zparts.append(body.strip())
    print("  %s —— %d 条" % (vol, n))

zhuawen = "\n\n".join(zparts) + "\n"
io.open(OUT_ZHUA, "w", encoding="utf-8", newline="\n").write(
    js_const("ZHUAWEN", zhuawen,
             r"24-知识库\02-条目\*.md 然后重跑本脚本"))
print("生成 %s  —— %d 条 / %d 字符" % (OUT_ZHUA, zn, len(zhuawen)))

