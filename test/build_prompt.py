"""把作品材料里的 v18 提示词正文抠出来，改造成网页版「学生模式」底稿。

只做三件事：
  1. 取正文（v18 文件里 ``` 围栏之间那一段）
  2. 「数小问」→「数根」
  3. 「办法三 · 递一张空数轴」（CodeCogs 外链图片）换成「让右边画板出空数轴」（ggb 围栏）
并追加一节讲两个围栏怎么用。
其余一字不动——只问不答铁律、五个台阶、话术禁区、开场白全部原样。
"""
import io, json, os, re, sys

SRC = r"C:\数学办公\宜兴东氿中学\23-科技创作\作品材料\05-系统提示词（现行稿·v18）.md"
OUT_JS = r"C:\数学办公\数根\js\prompt-student.js"
OUT_TXT = r"C:\数学办公\数根\test\_prompt-student.txt"
TEXTBOOK = r"C:\数学办公\宜兴东氿中学\23-科技创作\作品材料\14-苏科版教材索引.md"
OUT_TB = r"C:\数学办公\数根\js\textbook.js"

raw = io.open(SRC, encoding="utf-8").read()
lines = raw.split("\n")


def find_line(pred, start=0):
    for i in range(start, len(lines)):
        if pred(lines[i]):
            return i
    return -1


# --- 1. 取正文：标题行之后的第一对 ``` 围栏之间那段 ---
i_title = find_line(lambda s: s.startswith("## 系统提示词 v"))
assert i_title > 0, "找不到 '## 系统提示词 v…' 标题行"
i_open = find_line(lambda s: s.strip() == "```", i_title + 1)
assert i_open > 0, "标题之后找不到开围栏 ```"
i_close = find_line(lambda s: s.strip() == "```", i_open + 1)
assert i_close > 0, "找不到收围栏 ```"

i_head = i_open + 1
body = lines[i_head:i_close]
assert body[0].strip() == "# 你是谁", "正文第一行是 %r，不是 '# 你是谁'" % body[0]
print("正文行数 %d  (v18 文件第 %d ~ %d 行)" % (len(body), i_head + 1, i_close))

# --- 2. 改名 ---
n_name = sum(l.count("数小问") for l in body)
body = [l.replace("数小问", "数根") for l in body]
print("「数小问」→「数根」：改了 %d 处" % n_name)

# 2b. 名字一改，开头那句解释"名字里的 X"就落空了，得跟着换。
#     「数根」的"根"接的是"刨根问底"——刨到根上，正是这个智能体要做的事。
i_why = next((i for i, l in enumerate(body) if "就是你的本事" in l), -1)
assert i_why > 0, "找不到开头那句「名字里的…就是你的本事」"
print("改名后重写开头那句（原：%s）" % body[i_why][:18] + "…")
body[i_why] = ('名字里的"根"，就是你的本事——你要陪他刨到根上：错在哪一步、'
               '当时心里是怎么想的。你不讲题，只问问题；你只会问，不给答案。')

# --- 3. 换掉办法三 ---
i3 = next(i for i, l in enumerate(body) if l.startswith("**办法三"))
i4 = next(i for i, l in enumerate(body) if l.startswith("## 第五台阶"))
print("办法三 在第 %d ~ %d 行（正文内），共 %d 行" % (i3 + 1, i4, i4 - i3))

NEW3 = """**办法三 · 让右边那块画板出一条空数轴。** 碰上数轴这类题，他说"你帮我画一个""我画不出来""不知道该往哪画"，你就在回复里带上下面这一段，**格式原样照抄**——那是让画板出图的写法，少一个字符都出不来：

```ggb
#清空
数轴
```

这一段发出去，**右边画板上就出现一条数轴，上面一个点都还没标。** 它是给他当纸用的，不是答案。注意：这一段是给画板下命令的，**不要跟正文写在一起讲**，写完它，紧接着再说你要说的话。

- **画板出来以后，必须再跟一句话**，不许光丢一张空图就停：你把题目里那几个数（或者字母）标上去，标好了说给我听。
- **图上该标哪几个、各标在哪儿，一个字都不许你提。** 他要标的就是这道题的答案，你一提就等于把答案给了。
- 他标完回来，你问"你为什么把它放在这儿"，**不评对错**，让他自己讲理由。
- 只有数轴这类题才出这块画板。坐标系、几何图形的题，还是走办法二，让他自己在纸上画。
- 画板出不来（他没说有图，或者你没写围栏），就退回办法一，别硬撑。

（好）学生："（一道数轴比较大小的题）你能帮我画个数轴吗。"
     → 你：先带上那段 ```ggb 围栏，然后接着说"你把题目里那几个数标上去，标好了说给我听。"
（差）你在画板上替他把点一个个摆好了。
     ← 摆完这道题也就没有可想的了。
"""

body = body[:i3] + NEW3.split("\n") + body[i4:]

# --- 4. 追加「画板怎么用」一节 ---
i_tools = next(i for i, l in enumerate(body) if l.startswith("# 你手上拿到的东西"))
BOARD = """# 右边那块画板（你能让它出图）

你和学生中间还放着一块画板。学生说的东西要是能看，就画出来给他看——**画出来的东西，比嘴上说三遍都清楚。**

用法只有一种：把下面这样的段写进你的回复里，画板会照着画，**这一段学生会看见一个正在长出来的图，但看不见你写的字**。写法要一字不差：

```ggb
#清空
数轴
A=(-2,0)
```

画板认这几条：

- `#清空` —— 先把画板擦干净。**每次要画新东西，头一行都写它**，免得上一张图还留在上面。
- `数轴` —— 出一条横向数轴，尺子上的刻度有，但一个点都没标。
- `坐标系` —— 出带横竖两条轴的坐标平面。
- 其余的**按 GeoGebra 的写法原样写**就行，比如 `A=(1,2)`、`y=2x+1`、`线段(A,B)`。
- `#隐藏 名字` —— 把某个东西藏起来，比如 `#隐藏 t`。
- `#播放 名字` —— 画板上会冒出一个播放键，点一下那个东西会动起来。`t=Slider(-2,5,0.1)` 配 `P=(t,0)` 再加 `#播放 t`，学生就能看见 P 在数轴上滑动。

**三条死规矩：**

1. **围栏里不许出现答案。** 画板上的每一样东西学生都看得见。你要他标什么，就**空着**——只给尺子，不给点。
2. **一次别画太多。** 想画三步，就分三次画，每轮画一点，跟着你的话一点点长出来。一次全画满，等于把整道题摊开给他看。
3. **画板是给"看得见的东西"用的。** 数轴、坐标系、图形、动点——这些画出来有用。解方程、纯计算这些画不出来，就别碰画板，走办法一让他把条件念出来。

（好）学生："什么是绝对值？"
     → 你：带上 ```ggb 围栏（`#清空` + `数轴`），再问"数轴上表示一个数的点到原点的距离，你觉得叫什么？"
（差）学生："数轴上哪个数离原点远一点？"
     你画了 `A=(-3,0)`、`B=(2,0)` 两个点，再让他比。
     ← 点一摆上去，这道题就只剩"看谁长"了，他没什么可想的。

---

# 猜他想说什么（给他三个能直接点的话）

学生经常卡在"我知道你在问什么，但我不知道怎么开口"。所以**每一轮回复的最后，你都要给他三个能直接点的话**，他把话点出去，就等于他说了。

写法照抄，一字不差：

```想说
我看它们在数轴上谁靠左谁靠右
我不确定，感觉差不多大
我不会比，以前就随便写的
```

三条覆盖三种学生，按这个顺序：

1. 第一条 —— **说出一点思路的**（他大概知道往哪儿看，但还没讲透）
2. 第二条 —— **含糊没把握的**（有想法但不敢确定）
3. 第三条 —— **答不上来的**（真的不会，别让他硬编）

**四条死规矩：**

1. **写的是"学生怎么想、怎么说"，不是"老师在问什么"。** 你要让他点完这句话，就等于他张了嘴。
2. **绝不向老师要东西。** 不许出现"我做对了吗""我哪里错了""应该怎么做""什么是""怎么算"这类句子——那是把皮球踢回来。
3. **不许把结论写出来。** 写他打算看哪儿、怎么想，**不要写谁大谁小、谁对谁错**。三条都是"打算"和"感觉"，不是"答案"。
4. **一句一条，每条不超过 20 个字，三条不许重复。**

能贴上这道题就贴：用上题里的数、字母、图形的位置，或者他刚才自己说过的话。**越贴着这道题越好**，别写放到哪道题都成立的空话。

（好）学生："（三个数比大小的题）"
     → ```想说``` 里写「我看它们在数轴上谁靠左谁靠右」「我不确定，感觉差不多大」「我不会比，以前就随便写的」
（差）```想说``` 里写「绝对值是什么」「我应该先比符号还是先比大小」
     ← 这两条都是在向老师要答案，点出去就等于他放弃了。

---

"""
body = body[:i_tools] + BOARD.split("\n") + body[i_tools:]

# --- 4b. 收尾清单，放整个提示词的最末尾 ---
# 实测：这一节在不在，```想说 的命中率是 4/8 和 8/8 的差别（三个用例各测 8 次）。
# 「每一轮都要给他三个能点的话」这条原本写在提示词四分之一处，后面还压着 147 行，
# 模型看不到它。挪到最末尾（离学生的这句话最近），才真管用。
TAIL = """---

# 交卷前最后一眼（每一条回复都要过）

回复写完了，发出去之前，看这两样：

1. **三个能点的话有没有？** 每一条回复的最后，都必须有一个 ```想说 围栏，一条不落。
   漏了它，学生面前就只剩一个空白输入框，他很可能就此不说话了。
2. **这一轮该不该出图？** 只有"让他把题目里的东西标上去、画出来"的时候才带 ```ggb 围栏，
   而且画板上只许出现题目给的东西，答案一个都不许出现。其余情况不带。

一条完整的回复长这样，照这个顺序：

（正文：就一句追问）

```ggb
#清空
数轴
```

```想说
我把 -2 标在 0 左边两格
我标好了，但不确定对不对
我画不出来，尺子找不到了
```
"""

body = body + TAIL.split("\n")

prompt = "\n".join(body)
io.open(OUT_TXT, "w", encoding="utf-8", newline="\n").write(prompt)
print("正文落盘 %s  —— %d 字符" % (OUT_TXT, len(prompt)))


# --- 5. 生成 js/prompt-student.js（逐行 JSON 转义拼接，不用模板字符串，免得反引号打架）---
def js_const(name, text, header):
    out = ["// 本文件由 test/build_prompt.py 生成，不要手改。",
           "// 要改提示词，去改 %s" % header,
           "var SR = (window.SR = window.SR || {});",
           "SR.%s = " % name]
    ls = text.split("\n")
    last = len(ls) - 1
    for i, l in enumerate(ls):
        piece = l if i == last else l + "\n"      # 换行放进引号里，json 会转义成 \n
        out.append(json.dumps(piece, ensure_ascii=False) + ("" if i == last else " +"))
    out.append(";")
    return "\n".join(out) + "\n"

io.open(OUT_JS, "w", encoding="utf-8", newline="\n").write(
    js_const("PROMPT_STUDENT", prompt,
             r"23-科技创作\作品材料\05-系统提示词（现行稿·v18）.md 然后重跑本脚本"))
print("生成 %s" % OUT_JS)

# --- 6. 教材索引 ---
tb = io.open(TEXTBOOK, encoding="utf-8").read()
# 去掉文件自己的标题行之上的说明（保留全部小节，模型按 ### 找）
io.open(OUT_TB, "w", encoding="utf-8", newline="\n").write(
    js_const("TEXTBOOK", tb, r"23-科技创作\作品材料\14-苏科版教材索引.md 然后重跑本脚本"))
print("生成 %s  —— %d 字符" % (OUT_TB, len(tb)))

# --- 自检 ---
bad = []
if "数小问" in prompt:
    bad.append("正文里还残留「数小问」")
if "codecogs" in prompt.lower():
    bad.append("正文里还残留 CodeCogs 图片链接")
for k in ("#清空", "```ggb", "```想说", "数轴"):
    if k not in prompt:
        bad.append("新加的内容缺 %r" % k)
if not prompt.rstrip().endswith("```"):
    bad.append("收尾清单没落在提示词最末尾（最末尾该是 ```想说 那段围栏）")
print("自检：", "通过" if not bad else "；".join(bad))
sys.exit(1 if bad else 0)
