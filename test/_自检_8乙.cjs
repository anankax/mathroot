// probe_blueprint6 的 8乙 那道闸 —— **两个方向一起跑**的自检。
//
// 为什么要单独有这么一份（2026-10-06 夜）：
//   8乙 这道闸今晚被改过第三次，三次**全是尺子自己的毛病**（看 probe_blueprint6.cjs 里那段注释）。
//   改尺子的危险在于：**把闸放宽之后，它往往就不再会红了** —— 于是"绿"变成一句空话，
//   谁也不知道它到底还量不量得动。所以每改一次，都要当场证明它**两个方向都还动**：
//     · 该放行的要放行（今晚被误判的那份 105 字回话）；
//     · 该逮住的照样逮住（真·空手回来那种）。
//   这就是记忆里那条「**把反例做进每一步**」：只跑顺向，"这把尺子在坏东西上红过"就没人敢信。
//
// 跑法：node test/_自检_8乙.cjs
//
// ⚠ 判据必须跟 probe_blueprint6.cjs 里**那一份**逐字一致。改了一边忘了另一边，
//   这份自检就变成了在量一个**产品里不存在的判据**（[[scanner-numbers-are-not-what-they-claim]]：
//   「两条尺子量出两个答案，因为其中一把量的是产品里不存在的路」）。
//   所以下面这一段是从那边**抄**过来的，抄的时候连着注释一起抄 —— 改了那边记得回来改这儿。
const 弱地板 = 60;
const 判 = (t) => {
  const 强 = /```ggb/.test(t) || (t.match(/答案/g) || []).length >= 1;
  const 弱 = (t.match(/[？?]/g) || []).length >= 3;
  return 强 || (弱 && t.length >= 弱地板);
};

const 案子 = [
  // ── 该绿的 ────────────────────────────────────────────────
  ['★★ 今晚被误判的那份（105 字，三道变式全带答案）',
    '变式一（换数字）\n解方程 2x - 4 = 6\n答案：x = 5\n\n变式二（换数字）\n解方程 -x - 3 = 7\n答案：x = -10\n\n变式三（换数字）\n解方程 x + 1 = 6\n答案：x = 5\n```', true],
  ['长形态（把题铺开写，~1500 字）', ('变式一 答案：x=5 变式二 答案：x=-10 ').repeat(60), true],
  ['★★ 合法但很短，只有画板指令（强判据不问长度）',
    '```ggb\nA=(1,1)\nB=(5,2)\n线段(A,B)\n```', true],
  ['很长但弱判据没过地板（那是"三个问号"那条才要地板的）', '？'.repeat(3), false],

  // ── 该红的 ────────────────────────────────────────────────
  ['★反例：空手回来（"好的我这就开始"）', '好的，我这就开始出三道变式。', false],
  ['★反例：空串', '', false],
  ['★反例：纯客套话，又臭又长，可一样成品没有',
    '好的老师，我明白了，这就按您说的办，马上把三道变式给您出好，请稍等。', false],
  //  ⚠ 这两个案子我第一版**写错了**，记一下：原来写的是「换什么数？难一点？要答案吗？」，
  //    一心想着"三个问号"，忘了里头那个**「答案」**——那是**强判据**，当场就把它放行了。
  //    于是自检报了一句"闸坏了"，其实坏的是**我的案子**（闸判得对：有"答案"字样，
  //    确实像在给东西）。写反例的时候，得把**自己刚加进去的词**也当成闸的一部分来查。
  ['★反例：只反问不给东西（三个问号够了，但短得可疑，且**不含"答案"二字**）',
    '换什么数？难一点？要几道？', false],
  ['★反例：三个问号 + **真够长**（≥60 字）—— 这条**本来就该绿**（弱判据成立）',
    '换什么数？难一点？要几道？您先说，我这边随时可以开始，出三道变式给您。'
    + '原题里那两个数字我可以换成别的整数，也可以保持题目结构不变，只改数。'
    + '您定个方向，我马上动手。', true],
];

let 过 = 0, 坏 = 0;
for (const [名, 文, 期] of 案子) {
  const got = 判(文);
  const 对 = got === 期;
  对 ? 过++ : 坏++;
  console.log((对 ? '  ✅ ' : '  ❌ ') + 名 + '  → ' + got + (对 ? '' : '（期望 ' + 期 + '）'));
}
console.log('\n' + 过 + ' 对 / ' + 坏 + ' 错');
console.log(坏 ? '★ 自检没过 —— 这道闸现在不能信，别拿它的绿当证据'
  : '★ 两个方向都量得动：放得过该放的，也逮得住真·空手');
process.exit(坏 ? 1 : 0);
