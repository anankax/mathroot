// ★ 从画板命令里把那条多边形**还原出来**，算它的真实面积——这才是"画板上真是什么"。
//   为什么不从正文里读：正文是模型自己写的，它说 6 画板可以是 4×2。
//   要判"说没说假话"，就得拿模型的话去比**画板的几何**，不能拿它的话比我的话。
function 取多边形(命令) {
  const pt = {};
  let m;
  const re点 = /^[ \t]*([A-Za-z])\s*=\s*\(\s*(-?\d+(?:\.\d+)?)\s*,\s*(-?\d+(?:\.\d+)?)\s*\)/gm;
  while ((m = re点.exec(命令))) pt[m[1]] = [Number(m[2]), Number(m[3])];
  const pm = 命令.match(/多边形\s*\(\s*([^)]*)\)/);
  if (!pm) return null;
  const P = pm[1].split(',').map(s => s.trim()).filter(n => pt[n]).map(n => pt[n]);
  return P.length >= 3 ? P : null;
}
function 图的面积(命令) {
  const P = 取多边形(命令);
  if (!P) return null;
  let s = 0;
  for (let i = 0; i < P.length; i++) {
    const [x1, y1] = P[i], [x2, y2] = P[(i + 1) % P.length];
    s += x1 * y2 - x2 * y1;
  }
  return Math.abs(s) / 2;
}
function 图的周长(命令) {
  const P = 取多边形(命令);
  if (!P) return null;
  let s = 0;
  for (let i = 0; i < P.length; i++) {
    const [x1, y1] = P[i], [x2, y2] = P[(i + 1) % P.length];
    s += Math.hypot(x2 - x1, y2 - y1);
  }
  return s;
}
