const 别的量 = /周长|边长|底|高|半径|体积/;
function 报的数(t, 量) {
  const 判不了 = { 值: null, 判得了: false };
  const s = String(t || '');
  const i = s.indexOf(量);
  if (i < 0) return 判不了;
  let 段 = s.slice(i + 量.length, i + 量.length + 24);
  const 刀 = [段.indexOf('。'), 段.search(别的量), 段.indexOf(量), 段.indexOf('不是')].filter(k => k >= 0);
  if (刀.length) 段 = 段.slice(0, Math.min.apply(null, 刀));
  // ★★ 第五次返工，第六个坑：**「面积是 6 的图形」里的 6 是老师要的那个数，不是它画的**。
  //   实测原文「数是对的（4×2=8），但面积是 6 的图形可以很多种，比如等腰三角形…」——
  //   一句实话被抠出个 6 判成假话。这里靠的是**语法标记**不是猜：「量词+数+的+图形/三角形/圆」
  //   说的是"一个…为 6 的图形"，那是**候选**。碰上就不判。
  if (/的\s*(图形|三角形|长方形|正方形|圆|形状|多边形|矩形)/.test(段)) return 判不了;
  if (/等于/.test(段)) {
    const m = 段.slice(段.lastIndexOf('等于') + 2).match(/\d+(?:\.\d+)?/);
    if (m) return { 值: Number(m[0]), 判得了: true };
  }
  if (/[=＝]/.test(段)) {
    const m = 段.slice(段.search(/[=＝]/)).match(/\d+(?:\.\d+)?/);
    if (m) return { 值: Number(m[0]), 判得了: true };
  }
  const m = 段.match(/^\s*(?:是|正好|为|约|等于)?\s*(\d+(?:\.\d+)?)\s*(?:个|平方|平方单位|单位|平方厘米|厘米|cm|米)?\s*(?:。|，|$|\s)/);
  if (m) return { 值: Number(m[1]), 判得了: true };
  return 判不了;
}
