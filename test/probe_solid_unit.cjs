// 持续用：`修正立体` 的**纯函数**尺子（不开浏览器，一秒跑完）。
//
// 它是 `probe_square_unit.cjs` 的同族。为什么要单独用字符串量、不交给板子：
//   板子只看得见"建出来是 cube 还是什么都没有"，看不见"**截到了哪两个参**"——
//   `Cube(A,B)` 和 `Cube(B,A)` 都是 cube，`Cube(A,B)` 和 `Cube(A,B,C)` 也都是 cube。
//   要钉住"截的是**前两个**、门槛是 **3**"，只能在字符串这一层。
//
// ★ 钉住的规矩来自实测（直接 evalCommand，不过产品那一层）：
//   ▸ 元数（test/_solid.cjs）：Cube(A,B) ✓  (A,B,C) ✓  (A,B,C,D) ✗  (E)✗ (F)✗
//       Tetrahedron 同一刀。→ "多于 3 个"一律零产出，截到前两个**不可能更坏**；
//       而 3 个是合法的，截了就真砍坏 —— 门槛写在 3，不是 2。
//   ▸ 行首补名（test/_name.cjs）：裸写 `Cube(A,B)` 建出来的一堆对象里**没有** `正方体`
//       这个名字，可模型下一步就写 `展开图(正方体, t)` 去引用它 → 整段废。
//       而 `正方体=Cube(A,B)` 建出来里面**就有**（中文对象名画板完全收），
//       接上 `Net(正方体, t)` ✓。→ 行首裸写的，替它补上自己的名字。
//   ▸ 补名不显形（test/_label.cjs）：匿名 / `c=` / `正方体=` 三张截图**逐字节相同**
//       （同一 md5、47987 字节）。多一个名字，图上什么都没多。
//
// ★ 它从 `js/board.js` 源码里**现抠**函数（不是抄一份），实现改了这把尺子跟着变。
const fs = require('fs'), path = require('path');
const 源 = fs.readFileSync(path.join(__dirname, '..', 'js', 'board.js'), 'utf8');
const 头 = 源.indexOf('// ---- 修正立体');
const 尾 = 源.indexOf('function translate(', 头);
if (头 < 0 || 尾 < 0) { console.error('✗ 抠不到 `修正立体`（源码结构变了？）'); process.exit(2) }
const { 修正立体, 切顶层 } = new Function(源.slice(头, 尾) +
  '\nreturn {修正立体: 修正立体, 切顶层: 切顶层};')();
console.log('✓ 从 board.js 第 ' + 源.slice(0, 头).split('\n').length + ' 行抠到 修正立体\n');

let 坏 = 0;
const 该 = (标, 入, 期望) => {
  const 得 = 修正立体(入);
  const 对 = 得 === 期望;
  if (!对) 坏++;
  console.log('  ' + (对 ? '✓' : '✗') + '  ' + 标);
  if (!对) {
    console.log('        入：' + JSON.stringify(入));
    console.log('        该：' + JSON.stringify(期望));
    console.log('        得：' + JSON.stringify(得));
  }
};

console.log('══ 一、该截的：多给点的写法（行首裸写的同时补上名字）══');
该('四个点（模型实测写的那一种）', '正方体(A,B,C,D)', '正方体=正方体(A,B)');
该('五个点', '正方体(A,B,C,D,E)', '正方体=正方体(A,B)');
该('带赋值的（★已经有名字了，不许再补一个）', 'c=正方体(A,B,C,D)', 'c=正方体(A,B)');
该('★套在别人参数里的 —— 只截参、**不补名**（补了就多出个没人要的对象）',
  '净=展开图(正方体(E,F,G,H), t)', '净=展开图(正方体(E,F), t)');
该('元组坐标（★这一条同时验"按顶层逗号切"）',
  '正方体((0,0,0),(1,0,0),(2,2,0),(0,3,0))', '正方体=正方体((0,0,0),(1,0,0))');
该('英文名直接写', 'Cube(A,B,C,D)', 'Cube=Cube(A,B)');
该('四面体同一刀', '四面体(A,B,C,D)', '四面体=四面体(A,B)');
该('四面体英文名', 'Tetrahedron(A,B,C,D)', 'Tetrahedron=Tetrahedron(A,B)');
该('空格多写的', '正方体( A , B , C , D )', '正方体=正方体(A,B)');
该('立方体也叫这个名', '立方体(A,B,C,D,E)', '立方体=立方体(A,B)');

console.log('\n══ 二、★该截参但不该动别的 ══');
该('★三个点 —— 合法！截到 2 会把它砍成另一个形状（门槛写 3 就是为了这条）',
  '正方体(A,B,C)', '正方体=正方体(A,B,C)');
该('两个点', '正方体(A,B)', '正方体=正方体(A,B)');
该('三个元组', '正方体((0,0,0),(1,0,0),(2,2,0))', '正方体=正方体((0,0,0),(1,0,0),(2,2,0))');
该('两个元组', '正方体((0,0,0),(1,0,0))', '正方体=正方体((0,0,0),(1,0,0))');
// ★★ 这两条是"别把刀伸错地方"：棱柱／棱锥给四个点是**合法的**（底面就是那个四边形）
该('★棱柱(A,B,C,D) —— 不在表里，四点合法，一个字都不许动', '棱柱(A,B,C,D)', '棱柱(A,B,C,D)');
该('★棱锥(A,B,C,D) 同理', '棱锥(A,B,C,D)', '棱锥(A,B,C,D)');
该('别的命令原样不动', '球(A,2)', '球(A,2)');
该('展开图本身不动（动的只是它肚子里的正方体）', '净=展开图(c, t)', '净=展开图(c, t)');
// ★ 左边那把闸
该('★`画正方体(A,B,C,D)` —— 前面是汉字，不是命令', '画正方体(A,B,C,D)', '画正方体(A,B,C,D)');
该('普通赋值原样不动', 'c=线段(A,B)', 'c=线段(A,B)');

// ─────────────────────────────────────────────────────────────
// ★★ 红验。**每一把对照尺都跟真函数共用同一套规矩，只把被怀疑的那一格换掉** ——
//   这是前一版踩的坑：补名那一道是后加的，对照版要是不跟着补名，
//   "分得开"就变成"因为补名而分得开"，跟被验的那一格（门槛／切法）没半点关系。
//   绿的样子跟尺子坏了长得一模一样（[[scanner-numbers-are-not-what-they-claim]]）。
// ─────────────────────────────────────────────────────────────
const RE = /(^|[^一-龥A-Za-z0-9_])(正方体|立方体|四面体|Cube|Tetrahedron)\s*\(((?:[^()]|\([^()]*\))*)\)/g;
// 门槛：几参以上才截 ／ 切法：里层参数怎么切 ／ 补名：'行首'（真的）| '不补' | '全'
const 造 = (门槛, 切, 补名) => s => String(s).replace(RE, (_, 前, 名, 里) => {
  const ps = 切(里);
  const 体 = ps.length <= 门槛 ? 名 + '(' + 里 + ')'
    : 名 + '(' + ps[0].trim() + ',' + ps[1].trim() + ')';
  if (补名 === '全') return 前 + 名 + '=' + 体;
  if (补名 === '行首' && (前 === '' || /^\s$/.test(前))) return 前 + 名 + '=' + 体;
  return 前 + 体;
});
const 报 = (标, 探针, 对照, 该得) => {
  const 真 = 修正立体(探针), 假 = 对照(探针);
  const 分得开 = 真 === 该得 && 假 !== 该得;
  if (!分得开) 坏++;
  console.log('  ' + (分得开 ? '✓' : '✗') + '  ' + 标);
  console.log('        探针 ' + JSON.stringify(探针));
  console.log('        真函数给 ' + JSON.stringify(真) + '（该 ' + JSON.stringify(该得) + '）');
  console.log('        坏的那把给 ' + JSON.stringify(假) + ' → ' + (分得开 ? '分得开' : '★分不开，上面那条绿不能信'));
};

console.log('\n══ 三、★红验甲：门槛从 3 改成 2（其余同真函数）══');
报('"三个点留着"这条必须变红', '正方体(A,B,C)', 造(2, 切顶层, '行首'), '正方体=正方体(A,B,C)');

console.log('\n══ 四、★红验乙：把"顶层逗号"换成 `split(",")`（其余同真函数）══');
报('元组那条必须变红', '正方体((0,0,0),(1,0,0),(2,2,0),(0,3,0))',
  造(3, s => s.split(','), '行首'), '正方体=正方体((0,0,0),(1,0,0))');

console.log('\n══ 五、★红验丙：不补名（其余同真函数）══');
报('"行首裸写要补名"这条必须变红', '正方体(A,B,C,D)', 造(3, 切顶层, '不补'), '正方体=正方体(A,B)');

console.log('\n══ 六、★红验丁：**到处都补名**（其余同真函数）══');
报('"嵌套的不许补名"这条必须变红', '净=展开图(正方体(E,F,G,H), t)',
  造(3, 切顶层, '全'), '净=展开图(正方体(E,F), t)');

console.log('\n' + (坏 ? '✗ 有 ' + 坏 + ' 条不对' : '✅ 全过（含 4 条红验）'));
process.exitCode = 坏 ? 4 : 0;
