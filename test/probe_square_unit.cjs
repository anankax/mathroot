// 持续用：`修正方形` 的**纯函数**尺子（不开浏览器，一秒跑完）。
//
// ★ 为什么这一道要单独用字符串量，而不是全交给 probe_fix3.cjs 那把走浏览器的：
//   `修正方形` 是**改写式子的**活，它管的是"这一串字符进去、那一串字符出来"。
//   拿板子量只能看到"建出来的东西是四边形还是三角形"——**粒度不够**：
//     `正方形(A,B,C,D)` 不补参 → 四边形 ✓，补了参 → 整条失败 ✗  ← 这个分辨得出来
//     `正方形(A,B,C)`   不补参 → 三角形 ✓，补了参 → 失败   ✗  ← 这个也分辨得出来
//   可"**补成了什么参数**"在板子上看不出来（`Polygon(A,B,4)` 和 `Polygon(A,B,5)`
//   都是 polygon，一个是正方形一个是正五边形）。要钉住"补的是 4 不是别的"，
//   只能在字符串这一层。
//
// ★ 它从 `js/board.js` 源码里**现抠**函数（不是抄一份），实现改了这把尺子跟着变。
const fs = require('fs'), path = require('path');
const 源 = fs.readFileSync(path.join(__dirname, '..', 'js', 'board.js'), 'utf8');
const 头 = 源.indexOf('// ⚠ 参数允许写成');
const 尾 = 源.indexOf('function translate(', 头);
if (头 < 0 || 尾 < 0) { console.error('✗ 抠不到 `修正方形`（源码结构变了？）'); process.exit(2) }
const 修正方形 = new Function(源.slice(头, 尾) + '\nreturn 修正方形;')();
console.log('✓ 从 board.js 第 ' + 源.slice(0, 头).split('\n').length + ' 行抠到 修正方形\n');

let 坏 = 0;
const 该 = (标, 入, 期望) => {
  const 得 = 修正方形(入);
  const 对 = 得 === 期望;
  if (!对) 坏++;
  console.log('  ' + (对 ? '✓' : '✗') + '  ' + 标);
  if (!对) {
    console.log('        入：' + JSON.stringify(入));
    console.log('        该：' + JSON.stringify(期望));
    console.log('        得：' + JSON.stringify(得));
  }
};

console.log('══ 一、该补的：两参形式（体检里出现 7 次的那种）══');
该('光名字', 's=正方形(A,B)', 's=Polygon(A,B,4)');
该('不带赋值（直接建）', '正方形(A,B)', 'Polygon(A,B,4)');
该('参数两边有空格的', 's=正方形( A , B )', 's=Polygon(A,B,4)');
该('★坐标元组 —— 不接的话会变成一个**两条边的退化多边形**（那个也"成功"）',
  's=正方形((0,0),(2,0))', 's=Polygon((0,0),(2,0),4)');
该('小数坐标', 's=正方形((0,0),(2.5,0))', 's=Polygon((0,0),(2.5,0),4)');
该('★补的是 **4**，不是 3、不是 5 —— 板子上分辨不出来，只能在这儿钉',
  '正方形(A,B)', 'Polygon(A,B,4)');

console.log('\n══ 二、★不该补的：一个字都不许动 ══');
该('四顶点给全 → 本来就是 Polygon(A,B,C,D)，多补一个 ,4 会整条废掉',
  's=正方形(A,B,C,D)', 's=正方形(A,B,C,D)');
该('三个点 → 三角形，补参同样会废掉', 's=正方形(A,B,C)', 's=正方形(A,B,C)');
该('坐标元组三个以上', 's=正方形((0,0),(2,0),(3,3))', 's=正方形((0,0),(2,0),(3,3))');
// ★ 左边那把闸：名字前面是汉字的，不是命令
该('★`正方形点(A,B)` —— 「正方形」后面跟的是汉字不是括号', '正方形点(A,B)', '正方形点(A,B)');
该('★`正方形格(A,B)` 同理', '画正方形格(A,B)', '画正方形格(A,B)');
// ★ 别的命令不许被误伤（这条防的是"哪天有人把正则写宽了"）
该('别的命令原样不动', 'M=中点(A,B)', 'M=中点(A,B)');
该('普通赋值原样不动', 'c=线段(A,B)', 'c=线段(A,B)');

console.log('\n══ 三、★红验：把"补 4"改成"补 5"，上面第一条必须变红 ══');
// ★★ 为什么非要有这一节：我是**看着"这两条得是 4"去写实现**的，
//   万一哪天实现改成补别的数，上面那节会**照样绿**——因为期望是我照着实现抄的。
//   这一节当场换一个数，断言"确实分得开"：说明上面绿是因为补的是 4，不是因为这条没生效。
//   （绿的样子和尺子坏了长得一模一样，见 [[scanner-numbers-are-not-what-they-claim]]。）
const 补5 = s => String(s).replace(/正方形\s*\(\s*([^,()]+?)\s*,\s*([^,()]+?)\s*\)/g, (_, a, b) => 'Polygon(' + a + ',' + b + ',5)');
const 探针 = 's=正方形(A,B)';
const 分得开 = 修正方形(探针) !== 补5(探针);
console.log('  ' + (分得开 ? '✓' : '✗') + '  真函数给出 ' + JSON.stringify(修正方形(探针)) + '，"补 5"给出 ' + JSON.stringify(补5(探针)) + ' → 分得开');
if (!分得开) 坏++;

console.log('\n' + (坏 ? '✗ 有 ' + 坏 + ' 条不对' : '✅ 全过（含 1 条拆参红验）'));
process.exitCode = 坏 ? 4 : 0;
