const path = require('path'), fs = require('fs');

// ---- 把数根那几个 js 原样装进来（跟浏览器同一个 window 形状）----
// ⚠ chips.js 里是直接写 `SR.CHIPS = …`、自己没声明 SR——在 node 的假 window 里
//   它就是个未定义变量，一跑就 ReferenceError。所以前面补一句 `var SR = window.SR`。
//   （跟 probe_chain.cjs 同一个坑。）
const store = {};
const LS = {
  getItem: k => (k in store ? store[k] : null),
  setItem: (k, v) => { store[k] = String(v); },
  removeItem: k => { delete store[k]; }
};
const W = { SR: {} };
for (const f of ['config.js', 'chips.js']) {
  try {
    new Function('window', 'localStorage', 'navigator',
      'var SR = (window.SR = window.SR || {});\n' + fs.readFileSync(path.join(__dirname, '..', 'js', f), 'utf8'))(W, LS, { onLine: true });
  } catch (e) { console.log('装 ' + f + ' 炸了：' + e.message); process.exit(1); }
}
const SR = W.SR;
if (!SR.parseChain || !SR.inferStep || !SR.stepJump) {
  console.log('★ chips.js 里没找到 parseChain / inferStep / stepJump —— 上面那些判据一条都别信。');
  process.exit(1);
}

