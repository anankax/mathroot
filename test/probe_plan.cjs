//   它读错了，老师不会觉得是脚本错了，只会觉得是自己点错了（记忆里那条"检测脚本的数字
//   不是它宣称的那件事"就是这个形状）。所以这里的每条边角都对着一种真实的翻车：
//     ① 该认出来的没认出来  → 条子原地不动或掉回起点
