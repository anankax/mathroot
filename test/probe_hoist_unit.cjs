// 持续用：`提前滑块` 的**纯函数**尺子（不开浏览器，一秒跑完）。
//
// 为什么还要一把纯函数的：
//   ① 走浏览器那把（_hoist.cjs）只能量"这个点会不会动"。可 `提前滑块` 有几条闸
//      （上界不是纯数、名字被前文定过）**量出来的结果跟"没提"一样**，图上分辨不出来。
//      ★ 上一版我读 `SR.board.批内行` 想直接看排好的顺序——那是 run() 的闭包局部变量，
//      从外面取不到，返回 undefined，我那条**什么都没量到**，而屏幕上照样有行读数。
//   ② 这道加工是**纯字符串重排**，本来就该拿字符串量。走浏览器只是绕远。
//
// ★ 它从 `js/board.js` 源码里**现抠**函数（不是抄一份），所以哪天实现改了，
//   这把尺子量的还是真的那一个。
const fs=require('fs'),path=require('path');
const 源=fs.readFileSync(path.join(__dirname,'..','js','board.js'),'utf8');
const 头=源.indexOf('var RE_滑块行');
const 尾=源.indexOf('\n  // ---- ', 头);            // 下一个注释块 → `提前滑块` 到此为止
if(头<0||尾<0){console.error('✗ 抠不到 `提前滑块`（源码结构变了？）');process.exit(2)}
const 提前滑块=new Function(源.slice(头,尾)+'\nreturn 提前滑块;')();
console.log('✓ 从 board.js 第 '+源.slice(0,头).split('\n').length+' 行抠到 提前滑块\n');

let 坏=0;
const 该=((标,行,期望)=>{
  const 得=提前滑块(行.slice());
  const 对=JSON.stringify(得)===JSON.stringify(期望);
  if(!对)坏++;
  console.log('  '+(对?'✓':'✗')+'  '+标);
  if(!对){
    console.log('        该：'+JSON.stringify(期望));
    console.log('        得：'+JSON.stringify(得));
  }
});

console.log('══ 一、该提的（体检里真出现过的那几种）══');
该('滑块写在使用之后 → 提到开关行后面',
  ['__NEW__','__NUMLINE__','P=(t,0)','t=Slider(-2,2,0.01)','__HIDE__t','__PLAY__t'],
  ['__NEW__','__NUMLINE__','t=Slider(-2,2,0.01)','P=(t,0)','__HIDE__t','__PLAY__t']);
该('上界写成 pi（常数，算纯数）',
  ['__NEW__','P=(t,0)','t=Slider(0,pi/2,0.02)'],
  ['__NEW__','t=Slider(0,pi/2,0.02)','P=(t,0)']);
该('两个滑块都提，且保持原本的相对顺序',
  ['__NEW__','P=(t,0)','t=Slider(-2,2,0.1)','Q=(u,0)','u=Slider(0,5,0.1)'],
  ['__NEW__','t=Slider(-2,2,0.1)','u=Slider(0,5,0.1)','P=(t,0)','Q=(u,0)']);
该('已经在最前面 → 原样不动',
  ['__NEW__','t=Slider(-2,2,0.01)','P=(t,0)'],
  ['__NEW__','t=Slider(-2,2,0.01)','P=(t,0)']);
该('一个滑块都没有 → 原样不动',
  ['__NEW__','A=(0,0)','B=(2,0)','c=Segment(A,B)'],
  ['__NEW__','A=(0,0)','B=(2,0)','c=Segment(A,B)']);

console.log('\n══ 二、★不该提的（每一条都得挡住）══');
该('★闸①：上界里有别的名字（`距离(A,B)`）',
  ['__NEW__','A=(0,0)','B=(2,0)','P=(t,0)','t=Slider(0, Distance(A,B))'],
  ['__NEW__','A=(0,0)','B=(2,0)','P=(t,0)','t=Slider(0, Distance(A,B))']);
该('★闸①：上界是一个变量名',
  ['__NEW__','h=3','P=(t,0)','t=Slider(0, h)'],
  ['__NEW__','h=3','P=(t,0)','t=Slider(0, h)']);
该('★闸②：名字在**它前面**已经被定过',
  ['__NEW__','t=3','P=(t,0)','t=Slider(-2,2,0.1)'],
  ['__NEW__','t=3','P=(t,0)','t=Slider(-2,2,0.1)']);
// ⚠ 这条第一版写错了：我以为插回"原来的位置附近"，实现是把滑块插到
//   **所有开关行之后、第一条真命令之前**（`__NEW__` 后面）。实现更简单也更好——
//   滑块的参数是纯数，不依赖 A，提到 A 前面没有任何影响。改期望，不是改实现。
该('闸②：前面的 A 跟这个滑块无关 → 照提（插在开关行之后）',
  ['__NEW__','A=(0,0)','P=(t,0)','t=Slider(-2,2,0.1)'],
  ['__NEW__','t=Slider(-2,2,0.1)','A=(0,0)','P=(t,0)']);
// ⚠ 这条第一版也写错了：我写成"`用滑块(t)` 不动"——它**确实**没动（还在原地），
//   我只是没算到"滑块会被提到它前面"。而那个提前正是好事（它用的就是 t）。
//   换成一条真在验"非赋值行不会被动"的：中间那两条普通命令的相对顺序必须原封不动。
该('普通命令的相对顺序原封不动',
  ['__NEW__','A=(0,0)','B=(2,0)','P=(t,0)','t=Slider(0,1,0.1)','F=(t,1)'],
  ['__NEW__','t=Slider(0,1,0.1)','A=(0,0)','B=(2,0)','P=(t,0)','F=(t,1)']);
该('滑块后面还带别的东西 → 不认（闸很窄）',
  ['__NEW__','t=Slider(-2,2,0.1) # 这是注释'],
  ['__NEW__','t=Slider(-2,2,0.1) # 这是注释']);

console.log('\n══ 三、★红验：把闸拆掉，上面几条必须变红 ══');
// ★★ 为什么非要有这一节：我是先看着"这几条要挡住"去写闸的，
//   万一我把闸写反了（比如永远返回 true），上面"不该提"那节也会全绿 ——
//   因为它压根没走闸。**"绿的样子"和"尺子坏了"长得一模一样。**
//   这一节当场把闸换成"什么都提"，断言上面那几条**确实会红**：
//   说明上面绿是因为闸拦住了，不是因为这条测试根本没生效。
const 永远提=lines=>{
  const 提=[],留=[];
  for(const L of lines){
    if(/^([A-Za-z_一-龥][\w一-龥]*)\s*=\s*Slider\s*\(/.test(L)) 提.push(L); else 留.push(L);
  }
  if(!提.length) return lines;
  let at=0; while(at<留.length&&(!留[at]||留[at].slice(0,2)==='__')) at++;
  return 留.slice(0,at).concat(提,留.slice(at));
};
const 探针=['__NEW__','A=(0,0)','B=(2,0)','P=(t,0)','t=Slider(0, Distance(A,B))'];
const 真=提前滑块(探针.slice()), 假=永远提(探针.slice());
const 分得开=JSON.stringify(真)!==JSON.stringify(假);
console.log('  '+(分得开?'✓':'✗')+'  闸①那条，真函数和"什么都提"给出**不同**结果 → 闸真的在拦');
if(!分得开){
  坏++;
  console.log('        ⚠ 两者一样：说明闸①没起作用，或这条压根没走到闸上。');
  console.log('        真：'+JSON.stringify(真));
}
const 探针2=['__NEW__','t=3','P=(t,0)','t=Slider(-2,2,0.1)'];
const 分得开2=JSON.stringify(提前滑块(探针2.slice()))!==JSON.stringify(永远提(探针2.slice()));
console.log('  '+(分得开2?'✓':'✗')+'  闸②那条，两者也分得开 → 闸真的在拦');
if(!分得开2)坏++;

console.log('\n'+(坏?'✗ 有 '+坏+' 条不对':'✅ 全过（'+'含拆闸红验）'));
process.exitCode=坏?4:0;
