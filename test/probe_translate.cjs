// 翻译层（中→英命令名）的**纯 node 尺子**：不连浏览器、不连画板、不连网，一秒跑完。
//
// 为什么单独要这一把：
//   体检表 probe_figall 跑一场 ≈ 50 分钟，probe_zhcmd 也要真画板。
//   可"模型写的这句中文，被 board.js 翻成了什么"是**纯函数**——
//   它不该跟 53 句模型调用绑在一起才能问。改一条 CMD_MAP 就等半场体检，
//   等不起，最后就会变成"改完没量就推上去"。
//
// ★ 它量的是**翻译**，不是**能不能画**——这两件事必须分开，混一起会读出假结论：
//     `圆弧(A,B,C)` 翻成 `CircularArc(A,B,C)` 是"翻对了"，可画板认不认是另一回事
//     （见 probe_zhcmd.cjs，那边把英文名喂给真 applet 看 getObjectType）。
//     反过来，`优弧(A,B,C)` 翻不动是**对的**——它不是命令名，是"弧"的一种叫法。
//
// 用法：node test/probe_translate.cjs
//   退出码 0 = 全绿；1 = 有红的（改 CMD_MAP 前后拿它对一眼）
const path = require('path'), fs = require('fs');

