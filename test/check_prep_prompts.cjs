// ============================================================
// ★ 为什么非要有这一段：这份脚本最像的坏法不是"报错了"，是**什么都不报**——
//   名单空了、检测器写崩了，三类断言全部空转通过，屏幕上还是一片绿。
//   那正是记忆里那条"检测脚本的数字不是它宣称的那件事"。所以每一类都拿一个
//   **已知的坏东西**喂进去，看它红不红。
const selfBad = [];
// ① 同源：每一条都得真给得出两组关键词（空数组 = 那条断言根本没在查）
SAME.forEach(([why, needF, needL]) => {
  if (!needF.length || !needL.length) selfBad.push('同源条目「' + why + '」有一边是空的，等于没查');
});
// ② 正向：名单不能是空的
if (!REG.length) selfBad.push('EXAMPLE_CHIPS 是空的，"每条都找得到"空转通过');
// ③ 反向：**喂一句明知没登记的示范，必须被抓住**
const CANARY = '你接这句：这是一句故意没登记的话，拿来验尺子。';
let canaryHit = false;
String(CANARY).split('\n').forEach(raw => {
  const line = raw.trim();
  if (!LINE_HEADS.some(re => re.test(line))) return;
  const body = line.replace(/^[^：:]*[：:]/, '').trim();
  if (!REG.some(c => c === line || c === body || c.indexOf(body) >= 0 || body.indexOf(c) >= 0)) canaryHit = true;
});
if (!canaryHit) selfBad.push('反向检测器认不出一句明知没登记的示范 —— 它的"通过"没有意义');
