// 持续用：`修正正三角` 的**纯函数**尺子（不开浏览器，一秒跑完）。
//
// 它是 `probe_solid_unit.cjs` / `probe_square_unit.cjs` 的同族。为什么用字符串量、
//   不交给板子：板子只看得见"建出来是 triangle 还是 polygon 还是什么都没有"，
//   看得见"**补出来的第三个点在哪**"吗？看不见。而且两条路（三点／两点）**都建出东西**，
//   板子分不出哪个是哪个 —— 要钉住"两点必须走 `正多边形(A,B,3)`"，只能在字符串这层。
//
// ★ 钉住的这条规矩来自实测（test/_tri.cjs，直接 evalCommand，不过产品这一层）：
//     Polygon(A,B,C) ✓ → t1:triangle + 三条边
//     Polygon(A,B,3) ✓ → poly1:polygon（还自己补出第三个点 D）
//     Polygon(A,B)   ✓ → poly1:polygon，只有两个顶点，**退化**（不是等边三角形）
//     正三角形(A,B,C) ✗   正三角形(A,B) ✗   （画板没这个命令，返回 false、一件不建）
//   → 所以**不能**在 CMD_MAP 里写 `'正三角形': 'Polygon'`：那样两参那条会悄悄
//     变成退化多边形，不报错、也不是等边三角形。按元数分接才对。
//
// ★ 它从 `js/board.js` 源码里**现抠**函数（不是抄一份），实现改了这把尺子跟着变。
//   ⚠ 抠的范围从「修正立体」开头起 —— 因为 `切顶层` 定义在那儿，
//     只抠「修正正三角」那一段会 ReferenceError（这坑我当场踩过）。
const fs = require('fs'), path = require('path');
const 源 = fs.readFileSync(path.join(__dirname, '..', 'js', 'board.js'), 'utf8');
const 头 = 源.indexOf('// ---- 修正立体');
const 尾 = 源.indexOf('function translate(', 头);
if (头 < 0 || 尾 < 0) { console.error('✗ 抠不到（源码结构变了？）'); process.exit(2) }
const 修正正三角 = new Function(源.slice(头, 尾) + '\nreturn 修正正三角;')();
console.log('✓ 从 board.js 第 ' + 源.slice(0, 头).split('\n').length + ' 行起抠到 修正正三角\n');

let 坏 = 0;
const 该 = (标, 入, 期望) => {
  const 得 = 修正正三角(入);
  const 对 = 得 === 期望;
  if (!对) 坏++;
  console.log('  ' + (对 ? '✓' : '✗') + '  ' + 标);
  if (!对) {
    console.log('        入：' + JSON.stringify(入));
    console.log('        该：' + JSON.stringify(期望));
    console.log('        得：' + JSON.stringify(得));
  }
};

console.log('══ 一、三个点：给的点就是顶点，走 `多边形` ══');
该('★模型实测写的那一条', '三角形=正三角形(A,B,C)', '三角形=多边形(A,B,C)');
该('等边三角形也叫这个名', '等边三角形(A,B,C)', '多边形(A,B,C)');
该('简称', '正三角(A,B,C)', '多边形(A,B,C)');
该('★套在别人参数里的 —— 兜底那几张表够不着，只有这一层接得住',
  'q=旋转(正三角形(A,B), 60°, A)', 'q=旋转(正多边形(A,B,3), 60°, A)');
该('元组坐标（按顶层逗号切，不切坏）',
  '正三角形((0,0),(2,0),(1,2))', '多边形((0,0),(2,0),(1,2))');

console.log('\n══ 二、两个点：只有一条边，等边三角形得靠画板自己补 ══');
该('★这一条是整把刀的重点', '正三角形(A,B)', '正多边形(A,B,3)');
该('等边三角形两参同理', '等边三角形(A,B)', '正多边形(A,B,3)');
该('带赋值', 't=正三角形(A,B)', 't=正多边形(A,B,3)');
该('空格多写的', '正三角形( A , B )', '正多边形(A,B,3)');

console.log('\n══ 三、★别的元数一律不许猜 ══');
// ★ 为什么：四个点以上的"正三角形"是没意义的输入。替它挑一个形状＝替它编题。
//   让它原样失败、原样进"没认"清单，人一眼看得见 —— 这比悄悄给个形状强。
该('★一个点 —— 原样放行', '正三角形(A)', '正三角形(A)');
该('★零个点', '正三角形()', '正三角形()');
该('★四个点 —— 原样放行（哪怕 `Polygon(A,B,C,D)` 是合法的四边形）',
  '正三角形(A,B,C,D)', '正三角形(A,B,C,D)');

console.log('\n══ 四、★一个字都不许动 ══');
// ★ 左边那把闸（同 `修正方形`／`修正立体`）：前面是汉字就不是命令名。
该('★`画正三角形(A,B,C)` —— 前面是汉字，不是命令', '画正三角形(A,B,C)', '画正三角形(A,B,C)');
该('★`正多边形(A,B,3)` —— 正多边形里没有"正三角"这个词，不许碰', '正多边形(A,B,3)', '正多边形(A,B,3)');
该('★`正方形(A,B)` 不归它管（是 修正方形 的活）', '正方形(A,B)', '正方形(A,B)');
该('普通的三角形命令原样不动', '三角形=多边形(A,B,C)', '三角形=多边形(A,B,C)');
该('拿名字当参数用（后面跟的不是左括号）', 'd=距离(正三角形, A)', 'd=距离(正三角形, A)');
该('别的命令原样不动', '球(A,2)', '球(A,2)');
// ★ 同一条线上两个：必须都接住，不能只换头一个
该('★一行里两个', '正三角形(A,B,C)+正三角形(D,E)',
  '多边形(A,B,C)+正多边形(D,E,3)');

console.log('\n══ 五、★红验甲：把两参那条也接成 `多边形`，它必须与真函数分得开 ══');
// ★★ 为什么非要有：这一条正是"**为什么不干脆在 CMD_MAP 里映射名字**"的当场证明。
//   映射名字＝两条路都吐 `多边形`。那样两参那条给的是 `Polygon(A,B)` ——
//   实测**建得出来**（返回 true！）但是个**两顶点的退化多边形**。
//   "建得出来"会让它一路绿着过去，老师看见的是个不是等边三角形的东西。
const 只换名 = s => String(s).replace(
  /(^|[^一-龥A-Za-z0-9_])(正三角形|等边三角形|正三角)\s*\(((?:[^()]|\([^()]*\))*)\)/g,
  (_, 前, 名, 里) => 前 + '多边形(' + 里 + ')');
{
  const 探针 = '正三角形(A,B)';
  const 分得开 = 修正正三角(探针) === '正多边形(A,B,3)' && 只换名(探针) !== '正多边形(A,B,3)';
  console.log('  ' + (分得开 ? '✓' : '✗') + '  真函数给 ' + JSON.stringify(修正正三角(探针)) +
    '，"只换名"给 ' + JSON.stringify(只换名(探针)) + ' → 分得开');
  if (!分得开) 坏++;
}

console.log('\n══ 六、★红验乙：把两个门槛写反（2 走 `多边形`、3 走 `正多边形`），必须分得开 ══');
// ★ 另一头：上一节证明"两参不能按三参接"，这一节证明"三参也不能按两参接"——
//   两个方向都当场对撞一次，不然"分得开"只是我嘴上说的。
//   ⚠ 第一版这条我写成了"真函数 ≠ 某个固定常量"—— **那是恒真的**，
//     等于没验（[[scanner-numbers-are-not-what-they-claim]] 里"红验写成把 got 和 want 对调"那一款）。
//     这里改成**真的跑一遍写反的实现**再比。
const 门槛写反 = s => String(s).replace(
  /(^|[^一-龥A-Za-z0-9_])(正三角形|等边三角形|正三角)\s*\(((?:[^()]|\([^()]*\))*)\)/g,
  (_, 前, 名, 里) => {
    const ps = 里.split(',');
    if (ps.length === 3) return 前 + '正多边形(' + ps[0].trim() + ',' + ps[1].trim() + ',3)';
    if (ps.length === 2) return 前 + '多边形(' + 里 + ')';
    return 前 + 名 + '(' + 里 + ')';
  });
for (const 探针 of ['正三角形(A,B,C)', '正三角形(A,B)']) {
  const 分得开 = 修正正三角(探针) !== 门槛写反(探针);
  console.log('  ' + (分得开 ? '✓' : '✗') + '  ' + 探针 + '  真函数给 ' +
    JSON.stringify(修正正三角(探针)) + '，写反的给 ' + JSON.stringify(门槛写反(探针)) + ' → 分得开');
  if (!分得开) 坏++;
}

console.log('\n' + (坏 ? '✗ 有 ' + 坏 + ' 条不对' : '✅ 全过（含 2 条红验）'));
process.exitCode = 坏 ? 4 : 0;
