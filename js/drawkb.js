  function 进门(话, k) {
    var 中 = [];
    for (var i = 0; i < k.门.length; i++) if (话.indexOf(k.门[i]) >= 0) 中.push(k.门[i]);
    return 中;
  }

  // ------------------------------------------------------------
  //  翻哪一张：命中的词最长的那张排前面；一样长再看一共命中几个字。
  //  取前二。为什么是二：量下来第一张就中的是 14/17，**前二里中 17/17**——
  //  第二张不是"更保险"，是那三条（圆锥摊开 / 圆上的弦 / 动点求最值）真需要两张。
  // ------------------------------------------------------------
  function 翻(话) {
    var t = String(话 || '');
    if (!t.trim()) return [];
    var 进 = [];
    for (var i = 0; i < 卡.length; i++) {
      var 中 = 进门(t, 卡[i]);
      if (!中.length) continue;
      var 最长 = 0, 共 = 0;
      for (var j = 0; j < 中.length; j++) {
        共 += 中[j].length;
        if (中[j].length > 最长) 最长 = 中[j].length;
      }
      进.push({ 卡: 卡[i], 最长: 最长, 共: 共, 序: i });
    }
    if (!进.length) return [];
    进.sort(function (a, b) { return (b.最长 - a.最长) || (b.共 - a.共) || (a.序 - b.序); });
    return 进.slice(0, 2).map(function (x) { return x.卡; });
  }

