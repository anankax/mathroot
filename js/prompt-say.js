//
//   查下来的实情（都是量过的，不是猜的）：
//     ① 那三条是 js/chips.js 里一张**写死的表**，挑表只按工位 id 挑
//        （SR.fallbackChips 只看 work 一个参数），跟刚画了什么完全无关；
//     ② 网页里**本来就有**"跟着对话走"的那条路——js/render.js 认 ```想说 围栏、
//        js/chat.js 优先用模型写的那三句，可**六份提示词里「想说」两个字一次都没出现过**。
