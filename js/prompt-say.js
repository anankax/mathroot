//     ③ 更深一层：备课那三条写死**没问题**（"接着往下摆""这句我说不出口"是对任何内容
//        都成立的话），而作图这三条是**内容指令**（正方体、球、三维）——
//        等于把内容指令摆进了元指令的槽位。这才是病根。
//
// ★ 所以这一份只解决作图工位：要模型**看着自己刚画的那张图**写三句。
//   ⚠ 兜底一个字不动（js/chips.js 的 SR.CHIPS.draw 照旧）——免费通道那两颗小模型
