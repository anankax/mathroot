//     模型不写的时候老师面前不能是空的。命不好就退回今天这样，最坏等于没做。
//
// ★ 写法照抄 js/prompt-prep.js 的 PROMPT_PREP_TAIL：**位置必须排在最后一段**
//   （api.js 是在提示词之后才拼那两段附注的，这一块得排在附注后面，见 js/api.js 那段实测）。
//   自检那一招也是从那份搬来的——**不给形容词，给一个当场能做、做完知道自己错没错的动作**。
//   "别写套话"这句叮嘱对着小模型说一百遍没用（重话说多了反而更黏）。
