SR.ggbcmds = (function () {
  var 卡 = SR.GGBCMDS || [];

  // 翻：老师这一轮的话里命中了哪几条。返回的条目**最多 4 条**（跟 drawkb 一个道理：
  // 贴多了等于没贴，越长越没人读）。
  // ★ 排序：先按"命中的那个词有多长"（长 = 不像巧合），一样长再看条目在表里的先后。
  function 翻(话) {
    var s = String(话 == null ? '' : 话);
    if (!s) return [];
    var 中 = [];
    for (var i = 0; i < 卡.length; i++) {
      var 最长 = 0;
      for (var j = 0; j < 卡[i].门.length; j++) {
        var w = 卡[i].门[j];
        if (w && s.indexOf(w) >= 0 && w.length > 最长) 最长 = w.length;
      }
      if (最长 > 0) 中.push({ 卡: 卡[i], 最长: 最长, 序: i });
    }
    中.sort(function (a, b) { return (b.最长 - a.最长) || (a.序 - b.序); });
    return 中.slice(0, 4).map(function (x) { return x.卡; });
  }

  // 探针钩子：跟 drawkb 的 `记一次/上一轮` 同形，好让尺子核"真贴了哪几条"。
  var 上次 = [];
  function 记一次(条) { 上次 = (条 || []).map(function (c) { return c.名; }); }
  function 上一轮() { return 上次.slice(); }

  return { 卡: 卡, 翻: 翻, 记一次: 记一次, 上一轮: 上一轮 };
})();
