// ② 名册（2026-10-07，整改② 「六个工位是六件工具，不是一个椅子上轮流坐六个人」）——
//   底座讲完"你是谁"，紧接着讲"你手上能办哪几件活儿"。
//
// ★ 治的是什么：原来六格各写一份身份，**谁在最后谁说话**（备课那句
//   `你是陪他把这节课预演一遍的人` 压过底座的 `你是数根`），切一格像换了一个人。
//   现在身份只有底座一处，名册把六件事摆成**同一个人的六件工具**，
//   下面换的只是"手上拿的东西"。位置在底座之后、附录之前：先读到框架，再读这一格的细节。
//
// ★★ 名册**一个字都不许写死**——名字和"拿走什么"全部从 `SR.WORK_ORDER` +
//   `SR.WORKS[x].takes` 现算。写死就是第二份真源：加第七个工位那天，附录、chips、
//   landing 全补齐了，只有这里**安安静静地少一行**，没有任何一处会红（这一族栽过多次，
//   见记忆里"加一个工位要补的六张按工位分档的表"）。这里现算，那张表就少一张。
//
// ⚠ `takes` 是**写给老师看的**（首屏悬停那行），里面那个"你"指的是老师；搬进系统提示词
//   语境就翻了（那边"你"是数根）。所以一律把"你"换成"老师"，别原样搬——
//   不换的话模型会读成"我自己上传的本校版式"。
//   开头的 `拿走：` 也去掉：外面已经有"它：xxx"这个壳了，再来一个冒号是两层。
SR.名册 = function () {
  var 单 = [];
  var 序 = (SR.WORK_ORDER || []).slice();
  for (var i = 0; i < 序.length; i++) {
    var w = SR.WORKS && SR.WORKS[序[i]];
    if (!w) continue;
    var t = String(w.takes || "").replace(/^拿走\s*[：:]\s*/, "").replace(/你/g, "老师");
    if (!t) continue;
    单.push("- " + (w.label || 序[i]) + "：" + t);
  }
  // 半装配的页面（config.js 还没跑）就一个字都不加，别吐一个空标题出去。
  if (!单.length) return "";
  // ⚠ 件数**别写死**：加第七个工位那天，"六"会当场变成一个假数字
  //   （同族栽过一次：写死的件数在"加一件"那天报成"仪器不对"）。数出来。
  var 头 = [
    "# 你手上有" + 单.length + "件活儿",
    "",
    "老师挑一件交给你办。**换的只是你手上拿的东西，不是你**——" + 单.length + "件都是你在做，你一直是数根。",
    ""
  ];
  var 尾 = [
    "",
    "老师换不换，由外面的界面定（他点一下，或者一句话被认出来了）。**你自己不主动提换工具**——",
    "不说「要不要我顺手画一下」，也不问「这题要不要出变式」。手上这件活儿该怎么干就怎么干，干完就停。"
  ];
  return 头.concat(单, 尾).join("\n");
};
