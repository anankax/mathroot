"`α` 从 0 转到 90°，那块三角形就绕着 E 掀起来。**折痕落在哪，旋转中心就写哪个点**；要盖过去的那整块有四个点，就多转几个（`D2=旋转(D, α, E)`、`C2=旋转(C, α, E)`……）。",

"★ 平面上的对称、翻折、折叠，**一律不写 `#三维`**。",

"# 统计图",

"统计图画在**坐标系**上。数据先写成列表，再喂给统计图命令：",

