"要画**频数分布**这种成组的，横轴写组中值或组的下界都行，两个列表对齐就行。",

"# 三视图、展开图（实话）",

"★ 画板上**没有「三视图」这种一键出三格图的东西**，也**没有「展开图」命令**（GeoGebra 文档里的 `Net` 这个画板里不存在，实测什么都不建）。别写这两个命令——写了板上一声不响什么都没有。",

