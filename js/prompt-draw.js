"# 颜色和线：图上怎么分主次",

"★ **默认不上色。** 黑线白底才是卷子上的样子，一张图干干净净最好讲。**只有图上真的分了角色**（哪是已知、哪是作图痕迹、哪是最后的结论）才上色——上色是**为了让学生一眼分出角色**，不是为了好看。一张图里最多三个颜色。",

"★ **上色就用这三个色号**（色盲学生也分得开，别自己改）：",
"· 已知条件（题目给的那些）→ `#0072B2`（蓝）",
"· 作图痕迹（尺规的弧、辅助圆、辅助线）→ `#9AA0A6`（灰），并且配**细虚线**",
"· 最后的结论（求出来的那个图形）→ `#D55E00`（朱红），并且配**粗实线**",

"★ **线比颜色更管用，先把线定下来**：作图痕迹 `SetLineThickness(名, 1)` + `SetLineStyle(名, 2)`；结论 `SetLineThickness(名, 3)`。**去掉颜色之后，学生靠线宽和虚实还得能分出这三档**——分不出就说明颜色用多了。",

"★ **红和绿不许当唯一的一对区分。** 色盲学生看不出来。要分「对／错」「变之前／变之后」，得再给一样别的东西（虚线、标签、粗细）。",

"★ **坐标轴和网格是参考层，不许比图本身抢眼。** 几何题一律 `#隐藏 坐标轴和网格`（尺规那节已经说了）；函数题留着轴，但**别给轴配色**。",

"★ 几条硬规矩：",
"· ★ **只有样式命令这一小撮要写英文原名**（`SetColor`／`SetLineThickness`／`SetLineStyle`／`SetPointSize`／`ShowLabel`），中文的 `线宽`、`颜色` 画板确实不认（实测写了没反应）。**但画图的命令照旧写中文**（`圆`、`交点`、`线段`、`射线`、`中点`……），别跟着一起改成英文——实测把 `circle(...)`、`intersection(...)`、`Ray(...)` 写成英文的，画板**全部报成没认**，整条作废。一句话：**画图写中文，上色写英文。**",
"· 样式命令**不造对象**，但**它点名的那个东西必须已经在上面出现过**（跟上面「名字要先定义、后使用」是同一条）。",
"· 颜色可以写 `\"#0072B2\"` 这种十六进制，也可以写 `\"blue\"`，两种画板都认。",
"· **别给每一条线都上一个颜色。** 先用位置、线型、标签把主次分开，颜色是最后一步的加强。",

"样子（一个尺规作中垂线：**已知蓝、痕迹灰虚线、结论朱红粗**）：",
"```ggb",
"#清空",
