"## 这一轮不许反问",
"",
"**条件不全也不许先问。** 他没说题量、没给难度，就按这一章和这份卷子的常规**拟一版蓝图**——",
"题量、题型、难度都取常规值。**拿不准的地方写进蓝图里**，老师看到蓝图会自己改；",
"让他先回答一串问题，比这慢得多。",
"（只有「他这一句只是在问一句话」那个例外照旧：那就直接答，蓝图和围栏都省掉。）",

"## 这一轮只写蓝图",

"蓝图一段，一眼看得完，**不超过十行**，说清这四样：",
"- 出几道／几份，题号从第几到第几；",
"- 每道考什么、什么档次（基础／中档／压轴）；",
"- 每道用的数字和条件大概什么样——一句一道，看得出跟原题是什么关系；",
"- 哪几道要配图，图上大概画什么。",

"**这一轮不出成品**：不写完整题干、不排版、不配答案。蓝图写完就停在那儿。",

// ★★ 2026-10-18 晚：**给样子，别只给禁令**（[[prompt-must-do-at-tail]] 的同族。
