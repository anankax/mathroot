// ⑥ 蓝图闸门（2026-10-06，整改方案第六步）——「命题」「组卷」两格专用的收尾块。
//
// 要的是这么一件事：老师让出的东西是**要拿去印、拿去上课**的（几道变式、一整份卷子），
//   模型别一口气全出完，先把"我打算出什么"写成一段短的摆给他看一眼，他点一下才出。
//   作图**不开这一格**（要图就给图，快比稳重要）——照他说的话：
//   「命题、组卷打开（题干得确认），作图关掉」。
//
// ★ 为什么做成「两段 + 一个门」，而不是在正文里加一句"先问一下"：
//   · 小模型只认最后读到的东西（[[prompt-must-do-at-tail]]：同一份提示词，格式要求
//     在中段时 ```想说 命中 0/6～1/6，挪到末尾是 5/8 → 10/10）。而这一块要它干的事
//     比排版还难：**这一轮先别给答案**。所以它必须占住那两格"最后一段"的位置。
//     那两格现在没有别的收尾块（`tail`/`say` 都没开），这一块顶上那个位置正合适，
//     排在 js/api.js 的 buildSystem **最末**（那条 if 后面就是 return）。
//   · 更要紧的是**一次只读一件事**：该问的时候它看不到"直接出"那句话，
//     该出的时候它看不到"先问"那句话。所以是两块正文，由代码挑一块拼进去，
//     不是一块里写"什么时候问、什么时候出"。
//   · 门是**离散的关键词门**，跟 ④ 的 `SR.board.该看板`、`SR.drawkb` 的翻卡同一族：
//     "老师这一轮有没有点头"是个词面问题，不是分数问题（那套理由与实测见 drawkb.js 顶上）。
//
// ★★ 已知不牢靠的一处，写下来别当它不存在：
//   那颗「就按这个办」是**模型写的**，而它写的这几行要过 js/chips.js 的抄写闸
//   （`filterCopiedChips`：一字不差 + 六字雷同，命中就**整组作废**、落回本地兜底）。
//   命题这格最容易撞的就是「换个例子试试」这类示范词。作废之后那颗按钮就没了。
//   所以这个门**不认按钮，只认字**：老师自己打「就按这个办」照样过门（见下面的 点头词）。
//   ★ 没有去松 chips.js 那道闸：它上头挂着量过的断言（test/probe_chips.cjs、
//     test/check_prep_prompts.cjs），为这一格松它不划算。
//
// ★★ 另一处：产品自己发的修理指令**必须关掉这个门**。
//   `js/chat.js` 的 `去问`（画板有命令没认时，让模型重写一份 ```ggb）走的是**同一个工位**，
//   而命题这格是会画图的（`multiFig`），所以那一趟真会走到这儿来。
//   它手里那句话不是老师说的，是修理指令——要是给它拼一段"这一轮先别出成品"，
//   正好跟"把整份 ```ggb 重写一遍"顶牛。所以那条路传 `蓝图: false`，
//   跟它早就传着的 `沿用卡: true` 是同一个位置、同一个道理（见 js/api.js 的 buildSystem）。
//
// ⚠ 改这一块之前先看 test/probe_blueprint6.cjs：那里有两条反例——
//   点头那一轮**不许**再摆一次蓝图，作图那一轮两段都**不许**出现。
var SR = (window.SR = window.SR || {});

// ── 该问的那一轮（默认） ────────────────────────────────────────
SR.PROMPT_BLUE_ASK = [
"# 这一轮先别出成品：把打算出的东西先摆给老师看一眼",

"他要拿这份东西去印、去上课。出错了，赔上的不是一句话，是一节课。",
"所以这一轮：**只说你打算出什么**，等他说一声「就按这个办」，下一轮再出全套。",

"## 这一轮只写蓝图",

"蓝图一段，一眼看得完，**不超过十行**，说清这四样：",
"- 出几道／几份，题号从第几到第几；",
"- 每道考什么、什么档次（基础／中档／压轴）；",
"- 每道用的数字和条件大概什么样——一句一道，看得出跟原题是什么关系；",
"- 哪几道要配图，图上大概画什么。",

"**这一轮不出成品**：不写完整题干、不排版、不配答案。蓝图写完就停在那儿。",

"（只有一种情况例外：他这一轮**只是在问你一句话**——这道题难不难、这个条件够不够、",
"为什么这么改。那就照常答那一句，蓝图和围栏都省掉。",
"判断只要一个动作：**把他说的这句话当成一颗按钮按下去。**",
"按下去会**出来一件东西**（几道题、一份卷），就先给蓝图；按下去只**换来一句话**，就直接答。）",

"## 发出去之前最后一遍：在回复的最末尾摆一颗可点的按钮",

"在回复的**最末尾**（正文那句话的后面）写一个围栏，第一行固定就是这四个字：",

"```想说",
"就按这个办",
"```",

"网页会把它变成老师脚底下的一颗按钮——他懒得打字，点一下就把这句发回来，那就是他点了头，",
"下一轮你照蓝图出。",
"想得出他还想改哪儿，就往下面再写，**最多两行**（换成什么样的数、加一道、难度提一档）；",
"想不出来就**只写这一行**，别硬凑。",
"那两行要具体到他一看就知道改哪儿，别写「再详细讲讲」这种放哪儿都成立的空话。"
].join("\n");

// ── 点了头的那一轮 ──────────────────────────────────────────────
// ★ 短是故意的：这一轮要它**出活**，不是要它守格式。它排在提示词最末，
//   再长就是在跟"该出的题、该配的图"抢那点末尾优势。
SR.PROMPT_BLUE_GO = [
"# 老师点头了：照上一轮那份蓝图，这一轮出全套",

"他刚点了「就按这个办」。这一轮**直接出成品**：",
"该出的题全出出来，该配的图配上，该排的版排好——题号、题干、答案，一样都别缺。",

"他这一句里要是另外交代了改动，先把那一处改掉，其余照蓝图。",

"**不要再问一遍，也不要再摆一次蓝图。**"
].join("\n");

// ── 门 ────────────────────────────────────────────────────────
// 只做一件事：**老师这一句话是不是"点头"**。是 → GO，不是 → ASK。
//
// ★ 词表是**离散的**，不查分（跟 该看板 / drawkb 的翻卡同一族）。
// ★ 两条附加的约束，都是为了不让"顺口一提"被当成点头：
//   ① **点头是一句短话**（≤ 20 字）。"这道题就这样出，第三题再加个图，另外把第一题的
//      数字换成负的，难度提上去，答案也要"（36 字）这种又长又带改动，该重新给蓝图，
//      不该直接出。★ 阈值是**实测定下来的**：40 字那一版把上面那句放过去了。
//   ② 紧挨在词前头的是「不／别／没」→ 不算（"不要按这个办，先把第 2 题改小"靠这条挡）。
//      ⚠ 这两条是**挡误判**用的，不是判"他到底想不想要"——挡不住的那些交给 ASK 那段
//        里那个动作（"当成一颗按钮按下去"），那是软的一层，能兜。
// ★★ 这个文件里出现过一次的坑，写在这儿省得再犯：判"前一个字是不是否定"时，
//   `'不别没'.indexOf(前)` 里**前一个字可能是空串**（词句就在开头），而
//   `''.indexOf('')` 是 **0**——一句话正正好好等于「按这个办」时，会被当成
//   "前头有个否定"，于是**最短的那几句点头全被判成没点头**。
//   （实测：'按这个办'／'出吧'／'直接出'／'开始出' 全落这一档，而 '就按这个办' 是
//     靠词表里另一个词恰好命中才蒙对的。）所以下面按 `at > 0` 分开写。
SR.blueprint = {
  点头话: '就按这个办',
  最长: 20,

  点头词: [
    '就按这个办', '按这个办', '照这个办', '就按这个来', '照这个来', '按这个来',
    '就按这个', '就按你说的办', '就按你说的', '照你说的办', '照你说的来',
    '就这么办', '就这样办', '这么办', '就这样',
    '行，出吧', '可以，出吧', '出吧', '开始出', '直接出', '按蓝图出', '就是它了'
  ],

  是点头: function (话) {
    var t = String(话 == null ? '' : 话)
      .replace(/[\s，。、,.!！?？…—·:：;；"'“”‘’()（）\[\]【】]/g, '');
    if (!t || t.length > SR.blueprint.最长) return false;   // 长话里有"按这个办"往往是顺口一提
    for (var i = 0; i < SR.blueprint.点头词.length; i++) {
      var w = SR.blueprint.点头词[i]
        .replace(/[\s，。、,.!！?？…—·:：;；"'“”‘’()（）\[\]【】]/g, '');
      var at = t.indexOf(w);
      while (at >= 0) {
        if (at === 0) return true;                                  // 开头那一个字前面没有否定
        if ('不别没'.indexOf(t.charAt(at - 1)) < 0) return true;     // 前头不是否定 → 真点了头
        at = t.indexOf(w, at + 1);
      }
    }
    return false;
  },

  // 这一轮该拼哪一段。返回空串 = 一个字都不加（调用方照这个判）。
  段: function (话) {
    if (SR.blueprint.是点头(话)) return SR.PROMPT_BLUE_GO || '';
    return SR.PROMPT_BLUE_ASK || '';
  }
};
