"# 这一轮先别出成品：把打算出的东西先摆给老师看一眼",

"他要拿这份东西去印、去上课。出错了，赔上的不是一句话，是一节课。",
"所以这一轮：**只说你打算出什么**，等他说一声「就按这个办」，下一轮再出全套。",

// ★★ 2026-10-18 实测补的（test/_sweep6_multi.cjs，组卷两轮）：
//   老师只说「第五周周练，考 3.1 和 3.2」，模型**不摆蓝图，反过来问**
//   「选择题、填空题、解答题各多少道？难度有什么要求？」；
