// 学情工位的**算盘**：把一张成绩表算成"哪道题平均分最低"。
//
// ============================================================
// 为什么非得有这一份（2026-10-08）
// ============================================================
// 原来这一格的活儿是**整个交给模型**的：提示词里写着「从老师刚交来的那张表里，
// 把每道题的得分率读出来」。可模型**不会做这个算术**——它不是在算，是在**编**。
// 实测（孔老师自己那份假成绩表，10 人 10 题，每题满分 4 分，`p/grade_txt.json`）：
//   它排出来的名次：第 4、5、10 题垫底（**各 0%**），**第 6 题倒数第二（40%）**。
//   照表算一遍（`scoreunit.cjs` 第①组，手算核过）：第 4 题 50%、第 5 和第 10 题各 63%、
//   **第 6 题 85%——是全班最好的一道**。
//   ⇒ 名次基本是**反的**，而"错因"（「去分母时漏乘常数项」）也是编的——
//     表里一个字都没提学生错在哪。
// 提示词里当时已经写着「**一个数都不许自己编**」，照编不误。这一条是这个仓库量过的老账：
// **小模型认样子，不认禁令**——而那段"完整的回复长这样"的示范里，
// 每行都摆着一个百分数，「要算得分率」这件事就是这么传下去的。
//
// ⇒ 分工改掉：**算术归代码，说话归模型**。
//   这份文件负责：读表 → 定出哪些列是题号 → 算每题的平均分（有满分才算得分率）→ 排序。
//   模型只负责：把它自己出的那几道挑出来、照算好的顺序念一遍、每道说一句难点在哪。
//   它**一个数都不经手**，也就没有编的机会。
//
// ============================================================
// ★ 孔老师 2026-10-08 定的口径（改动前先看这条）
// ============================================================
//   「**没有满分就不给百分数，只给名次和平均分**」
//   周练每道题的满分不一样，没有满分这个分母就算不出得分率。**不猜**：
//   表里没有满分那一行，就一个百分数都不出现，只按平均分排，并且**当场说清这个口径**
//   （满分不明时，"平均分低"不等于"这道更差"）。
//
// ★ 表从哪来：`SR.files` 读出来的文本（.xlsx 直接读、CSV/TXT 直接读、粘进对话框的也算）。
//   所以这一层**只认文本**，不碰 xlsx 的音容笑貌——那是 js/files.js 的事。
var SR = (window.SR = window.SR || {});

SR.scores = (function () {

  // 一格里字面上像是"题号"的名字，排除掉
  var 不是题的头 = /学号|序号|编号|考号|姓名|学生|班级|总分|总成绩|合计|分数|得分|扣分|满分|分值|名次|班次|排名|等级|评价|评语|备注|时间|日期|客观题|主观题|小题分|大题分/;

  function 是数(s) { return /^-?\d+(\.\d+)?$/.test(String(s).trim()); }
  function 数(s) { return Number(String(s).trim()); }

  // ---- 拆行拆格 ----
  // 分隔符**从表里挑**，不写死：.xlsx 那条路给的是制表符（js/files.js 铺成文本时用的），
  // 老师从 Excel 里复制粘贴过来的是制表符，导出 CSV 是逗号，手打的可能是空格。
  // 挑法：哪个分隔符切出来的"列数中位数"最大就用哪个（都得 ≥2 列才算数）。
  function 挑分隔符(行们) {
    var 候选 = ['\t', ',', ';', '|'];
    var 最好 = '', 最好列 = 1;
    for (var i = 0; i < 候选.length; i++) {
      var 列数 = [];
      for (var r = 0; r < 行们.length; r++) 列数.push(行们[r].split(候选[i]).length);
      列数.sort(function (a, b) { return a - b; });
      var 中位 = 列数[Math.floor(列数.length / 2)] || 1;
      if (中位 > 最好列) { 最好列 = 中位; 最好 = 候选[i]; }
    }
    return 最好;   // 空串 = 没有分隔符（那就按空格切）
  }
  function 拆格(line, sep) {
    var a = sep ? String(line).split(sep) : String(line).trim().split(/\s+/);
    for (var i = 0; i < a.length; i++) a[i] = String(a[i]).replace(/^"|"$/g, '').trim();
    return a;
  }
  // 表头那格写成 `第3题` / `3题` / `3.` 都算题号 3
  function 当题号(s) {
    var t = String(s).trim().replace(/^第\s*/, '').replace(/\s*题$/, '').replace(/[.．、]$/, '');
    if (!/^\d+$/.test(t)) return 0;
    var n = Number(t);
    return (n >= 1 && n <= 200) ? n : 0;
  }

  function 解析(text) {
    var 行们 = String(text == null ? '' : text).split(/\r?\n/).map(function (s) { return s.replace(/\s+$/, ''); })
      .filter(function (s) { return s.trim(); });
    if (行们.length < 2) return { err: '这张表太小了（不到两行），看不出题号。', kind: 'notable' };

    var sep = 挑分隔符(行们);
    var 格们 = 行们.map(function (s) { return 拆格(s, sep); });
    var W = 0;
    for (var i = 0; i < 格们.length; i++) W = Math.max(W, 格们[i].length);

    // ---- 找表头：第一行有 ≥3 个非空格子的 ----
    var 头行 = -1;
    for (var r = 0; r < 格们.length; r++) {
      var 有 = 0;
      for (var c = 0; c < 格们[r].length; c++) if (格们[r][c]) 有++;
      if (有 >= 3) { 头行 = r; break; }
    }
    if (头行 < 0) return { err: '这张表里没找到一行像表头的（要有一行写着学号／姓名／题号）。', kind: 'notable' };

    // ---- 先扫一遍：哪一列**底下有数** ----
    // ★★ 这一步是 2026-10-08 拿他真人那份智学网明细表量出来的，别省。
    //   那种表的表头里，紧挨着「满分」标签还有一个**单独的格子写着 `120`**（整卷满分），
    //   而 `当题号('120')` 是**认的**（120 落在 1~200 里）——于是凭空多出一列"第 120 题"。
    //   那一列底下**全是空的**：学生一个都没有、平均分 0，可它会挤进 题列 里，
    //   让整张表算出 18 道"有成绩的题"+1 道空题，最后还被判成"没读到学生成绩"。
    //   一个**空列**冒充了一道题，把好端端一张表整成了废表。
    //   判据又简单又硬：**一列里一个数都没有，它就不可能是某道题的得分。** 先扫，再认。
    var 列有数 = [];
    for (var c0 = 0; c0 < W; c0++) 列有数.push(false);
    for (var rr = 头行 + 1; rr < 格们.length; rr++) {
      for (var cc = 0; cc < 格们[rr].length; cc++) { if (!列有数[cc] && 是数(格们[rr][cc])) 列有数[cc] = true; }
    }

    // ---- 哪些列是题号 ----
    // ★ 题号那一格除了光秃秃的 `7`，还有几种常见写法，都得认：
    //   · `第7题` / `7题` / `7.`  → `当题号()` 里剥掉前后缀
    //   · **`11-18`** —— 智学网把八道小题**并成一列**（分值也是八道合起来的）。
    //     ⚠ 这一种原来**整列被丢掉**，而它常常正是全班最烂的一列（他那份表里
    //     第 26 题那一列就是 38.75%，垫底）。丢掉它不报错、不显示、一个字都不说——
    //     正是"空读数"那一族最阴的坏法（[[scanner-numbers-are-not-what-they-claim]]）。
    //     现在当成**一列合并的题**留着，标签照原样写「第 11–18 题」，老师一眼看得出
    //     那是八道合起来的（得分率仍然可比，因为它就是那八道的合成分）。
    var 题列 = [];
    for (var c2 = 0; c2 < W; c2++) {
      var h = (格们[头行][c2] || '');
      if (!h || 不是题的头.test(h)) continue;
      var 从 = 0, 到 = 0, n = 当题号(h);
      if (n) { 从 = n; 到 = n; }
      else {
        var mg = String(h).replace(/\s/g, '').match(/^(\d{1,3})[-–—~～](\d{1,3})$/);
        if (mg) { 从 = Number(mg[1]); 到 = Number(mg[2]); }
      }
      if (!从 || 从 < 1 || 从 > 200 || 到 < 从 || 到 > 200) continue;
      if (!列有数[c2]) continue;                      // ★ 空列不是题
      题列.push({ 列: c2, 题号: 从, 到: 到, 标签: 从 === 到 ? String(从) : (从 + '–' + 到) });
    }
    if (!题列.length) {
      // ★★ 这一档是**他的成绩表里最常见的一种**（2026-10-08 拿他机器上 7 个真文件试出来的）：
      //   `19-周考成绩/` 底下那几份（B4周考成绩、B2周练成绩…）表头都只有
      //   「学号 姓名 分数 扣分 名次」——**只有总分，没有每题一列**。
      //   这种表里**根本不存在**"哪道题更差"这个信息，不是我们没读出来。
      //   所以给它一个**专门的说法**（api.js 认这个 `kind:'noq'`），
      //   好让模型能对老师说清楚"你要的是哪种表"——
      //   而不是笼统地回一句"把成绩表发给我"，老师会再发一遍同一份，来回打转。
      var 像成绩表 = false;
      for (var hb = 0; hb < 格们[头行].length; hb++) {
        if (/学号|姓名|学生|分数|考号|总分/.test(格们[头行][hb] || '')) { 像成绩表 = true; break; }
      }
      return {
        err: 像成绩表
          ? '这张表是一份**只有总分**的成绩表（表头是学号／姓名／分数那一类），里面**没有"每题一列"**，' +
            '所以排不出"哪道题更差"——这个信息这张表里根本没有。'
          : '这张表里没有"每题一列"的那种排法（表头上要写着 1、2、3… 这样的题号）。',
        kind: 像成绩表 ? 'noq' : 'notable'
      };
    }

    // ---- 汇总行：班级均分／班级得分率%／年级均分／年级得分率% 那些 ----
    // ★★ 这一档是 2026-10-08 拿他真人那份智学网明细表量出来的，**最要紧的一处**：
    //   那张表在 50 个学生后面还跟着 4 行汇总（班级均分、班级得分率%、年级均分、年级得分率%），
    //   它们**每一列都有数**，所以原来被**当成 4 个学生算了进去**——
    //   第 1 题的平均分本该是 2.88，读出来成了 6.37（50 个学生 + 4 行汇总一起平均）。
    //   屏幕上完全正常：就是个两位小数，谁也看不出里面混进了四行"平均"。
    //   判据：**这一行的第一格不是数字**（学生行第一格是序号），而且写着均分／得分率那一类字。
    // ★ 顺带捞一件好事：那张表**自己就带着「班级得分率%」这一行**（智学网算好的）。
    //   有它就用它——比我们拿 50 个学生再算一遍更准，而且跟老师屏幕上那张表
    //   **逐字对得上**（这一点比"准"还重要：他会拿两边核对）。
    var 汇总行 = {}, 汇总首 = {}, 得分率行 = -1, 得分率行们 = [];
    var 汇总之 = /均分|平均分|平均|得分率|及格率|优秀率|最高|最低|合计|统计|标准差|难度|区分度|年级|班级|方差/;
    for (var r4 = 头行 + 1; r4 < 格们.length; r4++) {
      var 首 = '';
      for (var c4 = 0; c4 < 格们[r4].length; c4++) { if (格们[r4][c4]) { 首 = String(格们[r4][c4]); break; } }
      if (!首 || 是数(首) || !汇总之.test(首)) continue;
      汇总行[r4] = true; 汇总首[r4] = 首;
      if (首.indexOf('得分率') >= 0) 得分率行们.push(r4);
    }
    // 老师要的是**他自己那个班**：优先「班级得分率」，没有再退到第一个得分率行。
    for (var s1 = 0; s1 < 得分率行们.length; s1++) {
      if (汇总首[得分率行们[s1]].indexOf('班级') >= 0) { 得分率行 = 得分率行们[s1]; break; }
    }
    if (得分率行 < 0 && 得分率行们.length) 得分率行 = 得分率行们[0];

    // ---- 满分那一行（有就用；没有就是孔老师定的那一档：不给百分数）----
    var 满分 = {}, 满分行 = -1, 满分对不齐 = false;
    for (var r2 = 0; r2 < 格们.length; r2++) {
      if (r2 === 头行 || 汇总行[r2]) continue;
      for (var c3 = 0; c3 < 格们[r2].length; c3++) {
        var t = String(格们[r2][c3] || '').replace(/\s/g, '');
        if (/^(满分|满分值|分值|每题满分|该题满分|满分：?)$/.test(t)) { 满分行 = r2; break; }
      }
      if (满分行 >= 0) break;
    }
    if (满分行 >= 0) {
      for (var k = 0; k < 题列.length; k++) {
        var v = 格们[满分行][题列[k].列];
        if (是数(v) && 数(v) > 0) 满分[题列[k].题号] = 数(v);
      }
    }

    // ---- 每道题：人次、总分、平均 ----
    var 累 = {};
    for (var k2 = 0; k2 < 题列.length; k2++) 累[题列[k2].列] = { 次: 0, 和: 0 };
    var 学生 = 0;
    for (var r3 = 头行 + 1; r3 < 格们.length; r3++) {
      if (r3 === 满分行 || 汇总行[r3]) continue;
      var 有数2 = false;
      for (var k3 = 0; k3 < 题列.length; k3++) {
        var v2 = 格们[r3][题列[k3].列];
        if (是数(v2)) { 累[题列[k3].列].次++; 累[题列[k3].列].和 += 数(v2); 有数2 = true; }
      }
      if (有数2) 学生++;
    }
    if (!学生) return { err: '这张表里没读到学生成绩（题号列下面全是空的）。', kind: 'empty' };

    var 每题 = 题列.map(function (t) {
      var a = 累[t.列];
      var o = { 题号: t.题号, 到: t.到, 标签: t.标签, 人次: a.次,
                平均: a.次 ? a.和 / a.次 : 0, 满分: 满分[t.题号] || 0, 得分率: 0, 有率: false };
      // ★★ 得分率**不许从 `平均`（浮点）算**。2026-10-08 单测抓到的一例：
      //   第 8 题 23 分/10 人 = 2.3，可 2.3 在二进制里是 2.2999999999999998，
      //   再 /4*100 得 57.49999999999999 → Math.round → **57**，而正确答案是 58。
      //   差 1 个百分点，**屏幕上看着完全正常**（就是个整数百分数），
      //   老师拿着它排"先讲哪几道"——第 8、9 题挨着，这一格就会把次序弄反。
      //   治法：拿**整数**去算——和 × 100 /（人次 × 满分），
      //   2300/40 = 57.5（57.5 是二进制能精确表示的），round 得 58。
      //   ⚠ 这跟 [[scanner-numbers-are-not-what-they-claim]] 是同一族的坑：
      //     数本身没错，错的是它**怎么来的**。改这一行之前先把单测跑一遍。
      if (o.满分 > 0) { o.得分率 = Math.round(a.和 * 100 / (a.次 * o.满分)); o.有率 = true; }
      return o;
    });

    // ---- 表里自带得分率就用它的（压过我们算的） ----
    // 先记下"自己拿满分算出来"这一档；下面那行表里自带的会把它盖掉。
    var 得分率来源 = (每题.length && 每题.every(function (x) { return x.有率; })) ? '算' : '无';
    if (得分率行 >= 0) {
      var 取到 = 0;
      for (var k4 = 0; k4 < 题列.length; k4++) {
        var v4 = 格们[得分率行][题列[k4].列];
        if (!是数(v4)) continue;
        var f = 数(v4);
        if (f > 0 && f <= 1.5) f = f * 100;    // 表里写成小数（0.96）也算
        // ★★ 2026-10-08 真跑一轮模型抓出来的：**表里自带的那一行，一个数都不许动**。
        //   原来这儿写的是 `Math.round(f)`。智学网第 26 题那一格是 **38.75**，
        //   round 成 39；可紧接着简报里写着「这些百分数跟老师表上那一行**一模一样**」——
        //   **这句话是假的**，而模型眼前就摆着那张原件：它看见 39 跟 38.75 对不上，
        //   就自己"改正"成 38 报给老师。
        //   量出来的读数：次序全对、平均分全对、50%/60% 全对，**只有这一个数**被它照原件改掉。
        //   ⇒ 病根不在模型，在我这行四舍五入 + 一句不成立的保证。
        //   治法：保留表里原来的精度（38.75 就写 38.75）。这样"一模一样"是真的，
        //   模型照抄就是对的，老师屏幕上看见的也跟他自己那份表一个样。
        //   只抹二进制浮点的尾巴（0.3875*100 可能是 38.750000000000004），不动它的位数
        //   ——**这不是四舍五入，是去噪声**。
        每题[k4].得分率 = Math.round(f * 100) / 100; 每题[k4].有率 = true; 取到++;
      }
      if (取到) 得分率来源 = '表';
    }

    // ★★ 数不可信的时候**不给百分数**，不猜、也不把 >100 的截成 100。
    //   两条判据，都是**定义上的不可能**：
    //     ① 用了表里那一行 → 得分率不可能超过 100；
    //     ② 自己拿 满分 算的 → 某题的平均分不可能高过它自己的满分。
    //   中了任一条，说明那一行**整体错位**了（跟题号列对不上）。这时候报出来的
    //   会是 135% 这种东西，摆在老师眼前比什么都不报更糟。
    //   退回"只给平均分"那一档，口径跟"表里没有满分"是同一条：
    //   **没有可信的分母，就不给百分数**（孔老师 2026-10-08 定的）。
    //   ⚠ 不是把 >100 的截成 100——那是把假数修得看着更真。
    var 有得分率 = false;
    if (每题.length) 有得分率 = 每题.every(function (x) { return x.有率; });
    if (有得分率) {
      for (var m1 = 0; m1 < 每题.length; m1++) {
        if (每题[m1].得分率 > 100) { 有得分率 = false; 满分对不齐 = true; break; }
        if (得分率来源 === '算' && 每题[m1].满分 > 0 && 每题[m1].平均 > 每题[m1].满分 + 1e-9) {
          有得分率 = false; 满分对不齐 = true; break;
        }
      }
    }
    if (!有得分率) {
      得分率来源 = '无';
      for (var m2 = 0; m2 < 每题.length; m2++) 每题[m2].得分率 = 0;
    }

    // 低 → 高。有得分率就按得分率排（各题满分不一样，只有它能横着比）；
    // 没有就按平均分排——这时口径要在简报里**说清楚**（满分不明，只能看平均分）。
    var 按 = 有得分率 ? function (x) { return x.得分率; }
                     : function (x) { return x.平均; };
    每题.sort(function (a, b) { return (按(a) - 按(b)) || (a.题号 - b.题号); });

    return {
      表头行: 头行, 表头: 格们[头行], 题列: 题列, 学生数: 学生, 每题: 每题,
      有得分率: 有得分率, 得分率来源: 得分率来源, 满分对不齐: 满分对不齐,
      得分率行: 得分率行, 得分率行名: 得分率行 >= 0 ? 汇总首[得分率行] : '',
      汇总行们: Object.keys(汇总行).map(function (k5) { return 汇总首[k5]; }),
      满分行: 满分行,
      首题号: 每题.length ? Math.min.apply(null, 每题.map(function (x) { return x.题号; })) : 0,
      末题号: 每题.length ? Math.max.apply(null, 每题.map(function (x) { return x.到; })) : 0
    };
  }

  // 给提示词的那一段。**这是模型唯一能看到的数字来源**——它不许自己再算。
  //
  // ★ 拆成两层（`简报自` 吃解析结果、`简报` 吃文本）是**给 api.js 用的**：
  //   老师可能一次拖进来好几份东西（成绩表 + 一份学案），得先**挑出哪一份才是那张表**，
  //   再拿挑中的那一份写简报。挑法见 api.js 那个调用点——**谁算出来的题多谁算表**，
  //   这个判据比"文件名像不像成绩表"结实（文件名是老师自己起的，判不了）。
  //   ⚠ 别退回"取最长的那个文本段"：一份讲评学案比 40 道题的成绩表长得多。
  function 简报自(r, 题号) {
    if (!r || r.err) return '';
    var L = [];
    L.push('# 这一轮算好的学情（★ 下面每一个数都是**代码从表里算出来的**）');
    L.push('');
    L.push('★ **这些数你一个都不许改、不许重算、不许四舍五入成别的数**。你的活儿只有两件：' +
           '① 把你出的那几道挑出来（按题号）② 照下面这个**次序**念一遍，每道补一句难点在哪。');
    L.push('');
    // ★ 他出的题号那一行（2026-10-08 搬到这儿）。
    //   原来这行只写在**系统提示词的「口袋」那一段**里（js/api.js 里那句
    //   「- 他出的那几道的题号：第 … 题」，2026-10-03 加的时候就写明"为学情那一格"）。
    //   实测**读不到**：同一具请求体（req-user1.json）发六遍，两遍回
    //   「你的口袋里还没有题」——口袋明明是满的，26 个题号就摆在系统提示词里。
    //   跟着表一起挪到 user 那条消息上，题号和表挨着摆，它才认。
    //   ⚠ **传空数组 ≠ 不传**：`[]` 要写出「一个都还没有」，那正是提示词里规矩一(2)的
    //     判据（以前它的判据是"去系统提示词里翻口袋那一段"，跟"表到没到"是同一个毛病）；
    //     不传（老的调用点、单测）就当没有这件事，一个字都不加。
    // ★★ 2026-10-08 再补的一行**判词**（在块的最上面）。来路是一组消融实测：
    //   同一具真身请求体（req-user4.json，题号那行明明写着「第 1…26 题」）发六遍——
    //     原样              4/6 排对，**2/6 回「你的口袋里还没有题」**
    //     把规矩一(2)那句**可抄的拒答话**从 system 里删掉   4/6，拒答没了，但改抄**另一句**
    //                       canned（「表里没有这道题。」）——**删句子没用，它只是换一句抄**
    //     只在块**最上面加一行判词**（下面这个）        **6/6**
    //     删句子＋加判词                               **6/6**
    //   ⇒ 药不是"别说什么"，是"**把它该看出来的那件事，写成一行它看得见的字**"。
    //     判据从"你自己去下面那行里认出有没有题号"降成"读第一行"——小模型做得到的是后者。
    //   ⚠ 千万别在这行里写出那句拒答话（"你的口袋里还没有题"）——那是往它嘴边递台词；
    //     本仓库量过：**要禁的原话摆进提示词，反而更黏**。
    //   ⚠ 只有**传了题号**（哪怕是空数组）才写这行：不传的老调用点（`简报`、单测）
    //     一个字都不许多，否则"不传时整段跟以前逐字相同"那条断言会当场红。
    if (题号) {
      // ⚠ 这一行**必须写成"一行字"，不能写成一句"你要去做什么"的话**。第一版写的是
      //   「★ 这一轮他出过题了——他出的那几道就在下一行，你要做的就是照下面的次序把它们念出来」，
      //   真跑八遍里有一遍**把它当台词念了出来**，回复第一句就是这行字（同 [[prompt-must-do-at-tail]]
      //   那个"舞台指示被当台词抄"的家族）。改成**陈述句 + 两三个字**，它就抄不出口。
      L.push(题号.length
        ? ('★ 有题号（他出的那几道在下一行：共 ' + 题号.length + ' 道）。')
        : '★ 没有题号（下一行写着"一个都还没有"）。');
      L.push('');
      L.push(题号.length
        ? ('你出的那几道的题号：第 ' + 题号.join('、') + ' 题。')
        : '你出的那几道的题号：**一个都还没有**（口袋里是空的）。');
      L.push('');
    }
    // ★★ 2026-10-08 真跑一轮抓出来的：原来是「表里读到 **50 名学生、19 道题**
    //   （题号 1–26）」，模型回的第一句是「表里读到 50 名学生、**26 道题**」——
    //   它把括号里那个**上界**当成了题数。**栏数和题号不是一回事**（这张表第 11–18 题
    //   并成了一栏，19 栏才覆盖到第 26 题），两个数挨着写，小模型一定会串。
    //   治法：把"为什么栏数比题号少"这半句**明写出来**，并让最后一步改成照抄这一句。
    var 并栏 = [];
    for (var b1 = 0; b1 < r.每题.length; b1++) if (r.每题[b1].到 && r.每题[b1].到 !== r.每题[b1].题号)
      并栏.push('第 ' + r.每题[b1].题号 + '–' + r.每题[b1].到 + ' 题');
    L.push('表里读到 **' + r.学生数 + ' 名学生**；表格一共 **' + r.每题.length + ' 栏**，' +
           '覆盖第 ' + r.首题号 + '–' + r.末题号 + ' 题' +
           (并栏.length ? '（' + 并栏.join('、') + '在表里并成了一栏，所以栏数比题号少）' : '') + '。');
    if (r.有得分率 && r.得分率来源 === '表') {
      // ★ 这一档比"我们算的"还硬：它跟老师屏幕上那张智学网表**逐字一致**。
      L.push('得分率：这张表**自己就带着一行「' + (r.得分率行名 || '得分率') + '」**（智学网算好的）。' +
             '下面**用的就是它**，没拿学生再算一遍——所以这些百分数跟老师表上那一行**一模一样**。');
    } else if (r.有得分率) {
      L.push('满分：表里有「满分」那一行，每题满分按它算，所以下面给**得分率**。');
    } else if (r.满分对不齐) {
      L.push('得分率：这个问题**算不出来**——有一道题的得分率高过了"全对"那条线（或者平均分高过了它自己的满分），' +
             '说明表里那一行**整体错了一列**。**那一行不能用**，所以下面**一个百分数都不给**，只列平均分。');
      L.push('★ 这件事**要告诉老师**：让他核一下表里「满分」／「得分率」那一行是不是跟题目错位了。');
      L.push('★ 这个次序只能读成"平均分低的排前面"，**不能**说成"这几道更差"。');
    } else {
      L.push('得分率：**表里既没有每题满分、也没有得分率那一行**，算不出来。所以下面**一个百分数都不给**，' +
             '只列每题的平均分，按平均分从低到高排。');
      L.push('★ 这个口径要**照原话说给老师听**：满分不明，各题满分很可能不一样，' +
             '所以这个次序只能读成"平均分低的排前面"，**不能**说成"这几道更差"。');
    }
    L.push('');
    L.push('从低到高（低 = 先讲）：');
    for (var i = 0; i < r.每题.length; i++) {
      var x = r.每题[i];
      // ★ 合并列（`11-18`，八道小题并成一列）照原样写成「第 11–18 题」——
      //   别写成「第 11 题」，那道题在这张表里没有单独的分数。
      var 题面 = (x.到 && x.到 !== x.题号) ? ('第 ' + x.题号 + '–' + x.到 + ' 题') : ('第 ' + x.题号 + ' 题');
      var 行 = 题面 + '　平均 ' + 收数(x.平均) + ' 分';
      if (r.有得分率 && x.得分率 >= 0) 行 += '　得分率 ' + x.得分率 + '%';
      if (x.人次 !== r.学生数) 行 += '　（只有 ' + x.人次 + ' 人有分）';
      L.push(行);
    }
    L.push('');
    L.push('★ 上面**没有**提到的题号，就是表里没有它——照规矩二写「表里没有这道题」，不许替它编。');
    return L.join('\n');
  }
  function 简报(text) { return 简报自(解析(text)); }

  function 收数(n) {
    var s = (Math.round(n * 100) / 100).toFixed(2).replace(/\.?0+$/, '');
    return s === '' || s === '-' ? '0' : s;
  }

  return { 解析: 解析, 简报: 简报, 简报自: 简报自, 拆格: 拆格, 挑分隔符: 挑分隔符 };
})();
