//   所以只能在这一头挡：出口过滤。
//   ⚠ 提示词里每换一次示范，这里就得跟着换。test/probe_fence.cjs 的 EX 是同一份名单，
//     两边一起改，别只改一处（那边的数字就是靠这份名单才没骗人）。
//   ⚠ 2026-10-01 用 grep 逐条核过：**下面这三句是提示词里仅存的示范**
//     （rehearse 全量版和精简版各一处，收尾块里没有示范）。
//     原来那份还挂着六条更早版本的残留（"我照着题目把条件都标上去了"之类），
//     提示词里早就没有了——那种名单留着只会让人以为它在挡什么，其实在挡空气。已删。
SR.EXAMPLE_CHIPS = [
  '我看它们在数轴上谁靠左谁靠右', '我不确定，感觉差不多大', '我不会比，以前就随便写的'
];
// 抄了就整组作废（示范是按三句一组给的，命中一句基本就是整组搬）。
// 作废不是"留空"——chat.js 见它返回空，会落回下面的本地兜底，照样有得点。
//
// ★ 光比"整句一模一样"不够（2026-10-01 实测，DeepSeek 那 6 条里 5 条搬了示范）：
//   它抄的时候**总是改几个字**——
//     示范：我不确定，感觉差不多大      它写：我不太确定，感觉差不多
//     示范：我不会比，以前就随便写的    它写：我不会看，以前就随便写的
//   这些改法整句比对都漏掉。所以再加一道"六字雷同"：
//   把两边的标点空格全去掉，只要有一串连续六个字撞上，就按抄了处理。
//   （上面前两例撞上的是"感觉差不多"和"以前就随便写的"。）
//   ⚠ 宁可错杀：错杀的代价只是**换成下面那份本地兜底按钮**，照样有得点；
//     放过的代价是老师点一下就替学生说了一句提示词里的话，性质不一样。
SR.normChip = function (s) {
  return String(s == null ? '' : s).replace(/[\s，。、,.!！?？…—·:：;；"'“”‘’()（）\[\]【】]/g, '');
};
SR.EXAMPLE_GRAMS = (function () {
  var set = {}, CH = 6;
  SR.EXAMPLE_CHIPS.forEach(function (c) {
    var n = SR.normChip(c);
    for (var i = 0; i + CH <= n.length; i++) set[n.slice(i, i + CH)] = 1;
  });
  return set;
})();
SR.filterCopiedChips = function (lines) {
  var ls = (lines || []).filter(function (s) { return String(s).trim(); });
  if (!ls.length) return [];
  for (var i = 0; i < ls.length; i++) {
    var s = String(ls[i]).trim();
    if (SR.EXAMPLE_CHIPS.indexOf(s) >= 0) return [];            // 一字不差
    var n = SR.normChip(s);
    for (var j = 0; j + 6 <= n.length; j++) {
      if (SR.EXAMPLE_GRAMS[n.slice(j, j + 6)]) return [];       // 六字雷同
    }
  }
  return ls;
};

// ============================================================
//  这一轮走到第几档
// ============================================================
// ★ **纯前端推断，不靠模型写档号。** 为什么不派给模型：小模型一次只服从得了一件事
//   （config.js 那段实测）。让它写 ggb、写想说、还要它记得写"STEP=3"，第三件一定先丢。
//   而这件事前端本来就得知道——挑兜底按钮一直要判它。所以把那个判断提出来，
//   **进度条和兜底按钮共用这一份**，别在两处各写一套（写两套＝两处迟早对不上）。
//
// ★ 判的是**模型这一轮问的那句话**（prevAssistant），不是"数到第几轮"。
//   模型跳到哪一档是它按学生答话自己定的，只有它问出口的那句话能证明它到了哪儿。
//
// ★ 收尾那一档单独判：提示词里明写了"这一档问的是这类题的坑在哪儿，
//   不是他当时怎么写的"，所以它跟五档分得开，判完就固定在那儿。
// ★ 第一轮有个**上界**：最多只到 ①复述（除非它一上来就在追问／递台阶）。
//   起因是量出来的：备课工位第一轮只给了个课题名，模型回
//   「你先给我一道这节的题……或者你直接说说，这一节学生最容易在哪一步停下来」——
//   那句话里有个"哪一步"，被下面第二台阶的正则咬中，进度条就跳到了「定位」，
//   还把「复述」标成了"走完"。可学生这时候**一个字都还没说**，哪有定位这回事。
//   ★ 更要命的是同一轮里兜底按钮仍按第一档发（那边用的是**空**的 prevAssistant），
//     于是按钮说"这是第一档"、进度条说"已经到第二档"——两处打架。
//     进度条和按钮共用这一份推断，就得连这个上界也共用。
SR.inferStep = function (opts) {
  opts = opts || {};
  var prev = String(opts.prevAssistant || '');
  if (!prev) return 1;
  // 收尾
  if (/最容易栽在哪|错题本上写一句|用自己的话讲一遍|下次怎么躲开/.test(prev)) return 'close';
  // 第五台阶 · 肯定（正则沿用原来那一份，别改：它是"肯定到学生刚说的那句原话上"的形状）
  if (/这类题的关键|说出来了|这一步做得对|就是这一步/.test(prev)) return 5;
  // 第四台阶 · 给台阶（办法一/二/三 的问法）
  if (/画个图|画到哪儿算哪儿|一个一个念给我听|是不是当时觉得|先不管后面/.test(prev)) return 4;
  // 第三台阶 · 追问
  if (/为什么这么写|凭什么确定|换成别的数|哪个条件让你/.test(prev)) return 3;
  // 第一轮：到这儿就收，不再往下判定位（理由见上面那段）
  if (opts.first) return 1;
  // 第二台阶 · 定位
  if (/最没底|不对劲|最碍事|下一步打算|哪一步/.test(prev)) return 2;
  // 第一台阶 · 复述
  if (/第一步|怎么开这个头|念一下/.test(prev)) return 1;
  // 都没咬上：按"学生上一句是什么"退一档，宁可退到复述也不瞎跳
  var t = String(opts.lastUser || '').trim();
  if (t.length <= 20 && /不会|不知道|不懂|没思路|忘了|卡住|不会做|没听懂|想不起来|没想法/.test(t)) return 4;
  return 2;   // 第一轮的已经在上面收掉了，走到这儿必定不是第一轮
};

// 挑哪一档按钮。按工位分派，备课那一档再按推断出来的台阶挑。
//   opts: { work 工位 id, first 是不是第一轮,
//           lastUser 学生（老师替说的）上一句, prevAssistant 数根上一句 }
SR.fallbackChips = function (opts) {
  opts = opts || {};
  var work = opts.work || SR.DEFAULT_WORK;
  if (work === 'draw') return SR.CHIPS.draw;
  if (work === 'vary') return SR.CHIPS.vary;
  if (work === 'review') return SR.CHIPS.review;
  var step = SR.inferStep(opts);
  return SR.CHIPS.rehearse[step] || SR.CHIPS.rehearse[1];
};
