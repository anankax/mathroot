//   点一下就等于替学生开口，数根顺势问下一句。
//   那套东西的毛病不在字上，在**主体反了**：老师点开备课，看到一排学生的话，
//   界面上又没一个字说"你现在是在替学生说话"，他的原话就是
//   「下面这些选项也不知道是啥玩意儿」。详情见 js/prompt-prep.js 顶上那段。
//
//   ★ 现在是**导演的话**：数根摆链子（它演学生、也把老师该接的那句写出来），
