// 抄了就整组作废。
// 作废不是"留空"——chat.js 见它返回空，会落回下面的本地兜底，照样有得点。
//
// ★ 光比"整句一模一样"不够（2026-10-01 实测，DeepSeek 那 6 条里 5 条搬了示范）：
//   它抄的时候**总是改几个字**，整句比对全漏掉。所以再加一道"六字雷同"：
//   把两边的标点空格全去掉，只要有一串连续六个字撞上，就按抄了处理。
//   ⚠ 宁可错杀：错杀的代价只是**换成下面那份本地兜底按钮**，照样有得点。
SR.normChip = function (s) {
  return String(s == null ? '' : s).replace(/[\s，。、,.!！?？…—·:：;；"'“”‘’()（）\[\]【】]/g, '');
};
SR.EXAMPLE_GRAMS = (function () {
  var set = {}, CH = 6;
  SR.EXAMPLE_CHIPS.forEach(function (c) {
    var n = SR.normChip(c);
    for (var i = 0; i + CH <= n.length; i++) set[n.slice(i, i + CH)] = 1;
  });
  return set;
})();
SR.filterCopiedChips = function (lines) {
  var ls = (lines || []).filter(function (s) { return String(s).trim(); });
  if (!ls.length) return [];
  for (var i = 0; i < ls.length; i++) {
    var s = String(ls[i]).trim();
    if (SR.EXAMPLE_CHIPS.indexOf(s) >= 0) return [];            // 一字不差
    var n = SR.normChip(s);
    for (var j = 0; j + 6 <= n.length; j++) {
      if (SR.EXAMPLE_GRAMS[n.slice(j, j + 6)]) return [];       // 六字雷同
    }
  }
  return ls;
};

// ============================================================
//  链子摆到第几节
// ============================================================
// ★ **纯前端读，不靠模型另外写一个档号。** 为什么不派给模型单独去写：
//   小模型一次只服从得了一件事（config.js 那段实测）。但它**不用多写一个字**——
//   提示词本来就把节标题规定成 `第 X 节 · 名字`，那一行是链子的一部分，
//   前端顺手从里面读出来就行。
//
// ★ 2026-10-02 换掉了原来那套**正则猜问句**的做法。旧版要判"模型这一轮问的是
//   复述还是追问"，写了一大串词表（/最没底|不对劲|最碍事|哪一步/ …），还得出特例：
//   老师的课题名里带个"哪一步"就能把进度条顶到第二档，还得再补一条"第一轮不许往下跳"。
//   现在节号是模型自己标出来的，**读一个数字，不用猜**。
//   万一小模型把节号丢了，才退到按名字认（只认开头一小段），再认不出就**原地不动**。
SR.inferStep = function (opts) {
  opts = opts || {};
  var prev = String(opts.prevAssistant || '');
  if (!prev) return opts.first ? 1 : 0;

  // ① 节标题（提示词规定的写法）。`第 2 节`／`第2节` 都认。
  var m = /第\s*([1-5])\s*节/.exec(prev);
  if (m) return +m[1];

  // ② 节号丢了，只写了名字。只认**开头那一小段**——"定位""追问"这些词
  //    老师在正文里本来就会说，整段去搜一定会误判。
  var head = prev.slice(0, 60);
  var NAMES = [[1, /复述/], [2, /定位/], [3, /追问/], [4, /给台阶|递台阶/], [5, /肯定/]];
  for (var i = 0; i < NAMES.length; i++) if (NAMES[i][1].test(head)) return NAMES[i][0];

  // ③ 都认不出来：返回 0 = **原地不动**（paintStepBar 见 0 会 keep 住当前那一档）。
  //    ★ 这里**绝不能随手退回 1**：模型偶尔少写一个节号，进度条整个掉回起点，
  //      老师会以为是自己的操作把它弄回去了。
  return 0;
};

// 挑哪一档按钮。按工位分派。
//   opts: { work 工位 id, first 是不是第一轮,
//           lastUser 老师刚说的话, prevAssistant 数根上一句 }
SR.fallbackChips = function (opts) {
  opts = opts || {};
  var work = opts.work || SR.DEFAULT_WORK;
  if (work === 'draw') return SR.CHIPS.draw;
  if (work === 'vary') return SR.CHIPS.vary;
  if (work === 'material') return SR.CHIPS.material;
  // 讲评第一轮：数根刚把卷子上的题号列完，老师该挑讲哪一道了。
  // 之后就回到链子（他挑定一道、链子一开始，动作就跟备课一模一样）。
  if (work === 'review' && opts.first) return SR.CHIPS.review;
  if (work === 'prep' || work === 'review') return SR.CHIPS.chain;
  // ★ 走到这一行的只剩"没见过的工位 id"。给链子那套是**故意的**：
  //   五个工位里有两个（备课／讲评）本来就是链子，是这里的大多数。
  //   ⚠ 但别再让**新工位**落到这儿——2026-10-02 出材料就是这么被漏掉的。
  return SR.CHIPS.chain;
};
