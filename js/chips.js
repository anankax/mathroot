// 抄了就整组作废。
// 作废不是"留空"——chat.js 见它返回空，会落回下面的本地兜底，照样有得点。
//
// ★ 光比"整句一模一样"不够（2026-10-01 实测，DeepSeek 那 6 条里 5 条搬了示范）：
//   它抄的时候**总是改几个字**，整句比对全漏掉。所以再加一道"六字雷同"：
//   把两边的标点空格全去掉，只要有一串连续六个字撞上，就按抄了处理。
//   ⚠ 宁可错杀：错杀的代价只是**换成下面那份本地兜底按钮**，照样有得点。
SR.normChip = function (s) {
  return String(s == null ? '' : s).replace(/[\s，。、,.!！?？…—·:：;；"'“”‘’()（）\[\]【】]/g, '');
};
SR.EXAMPLE_GRAMS = (function () {
  var set = {}, CH = 6;
  SR.EXAMPLE_CHIPS.forEach(function (c) {
    var n = SR.normChip(c);
    for (var i = 0; i + CH <= n.length; i++) set[n.slice(i, i + CH)] = 1;
  });
  return set;
})();
SR.filterCopiedChips = function (lines) {
  var ls = (lines || []).filter(function (s) { return String(s).trim(); });
  if (!ls.length) return [];
  for (var i = 0; i < ls.length; i++) {
    var s = String(ls[i]).trim();
    if (SR.EXAMPLE_CHIPS.indexOf(s) >= 0) return [];            // 一字不差
    var n = SR.normChip(s);
    for (var j = 0; j + 6 <= n.length; j++) {
      if (SR.EXAMPLE_GRAMS[n.slice(j, j + 6)]) return [];       // 六字雷同
    }
  }
  return ls;
};

