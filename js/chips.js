//   ⚠ 措辞一改，`js/prompt-prep.js` 里"老师说了话你怎么动"那张对照表**必须同时改**——
//     那句话是喂给模型的，表里不认它，模型就得靠猜。改一处忘一处就是这个仓库最老的毛病。
//   ⚠ 只改**本机发出去的这句话**。模型自己**输出**的格式（`第 N 节 · 名字`）这一版不动：
//     动它要跟 chips.js 的正则、四份提示词、三把尺子一起动，得单独量一轮。
//     （正则已经先放宽成两套都认了，见下面 UNIT 那段。）
SR.stepJump = function (n) {
  // ★ 这一句要跟底下那个按钮（SR.CHIPS.chain 最后一条）**逐字对上**。
  //   原来写的是「整条链子从头到尾摆一遍，我拷走。」——两个毛病：
  //   ① 又是「摆」；② 它是这个动作的**第三种说法**，而 js/prompt-prep.js 那张
  //   "老师说了话你怎么动"的表里认的是「整条给我，我拷走」/「整条给我」。
  //   模型对着一张没有的说法，就只能猜——这正是这个仓库最老的那类毛病。
  if (n === 'close') return '整条链子给我，我拷走。';
  if (n === 'next') return '接着往下。';
  n = parseInt(n, 10);
  if (!n || n < 1) return '';
  // 回第 1 格是"重来"，措辞跟往下走不一样——老师点第一格多半是想重摆。
  return n === 1 ? '从第 1 个环节重来。' : ('走到第 ' + n + ' 个环节。');
};

