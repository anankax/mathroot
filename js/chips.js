// 「猜他想说」的三个按钮——本地兜底词库。
//
// ★ 为什么要有一份本地兜底（2026-10-01 实测，别删）：
//   本来是让模型在每轮回复末尾写一个 ```想说 围栏，网页照它渲染三个按钮。
//   在 DeepSeek 上这套是 8/8；换到免费通道就守不住了，而且两颗模型各坏一半：
//     glm-4v-flash（视觉，9B）——会丢角色。学生说"我不会"，它回
//       "好的，老师，这道题我不会。请问我应该如何比较 -2 和 1 的大小呢？"
//       它把自己当成学生了。调了四轮提示词（5303→3165 字、换收尾、拆剧本、禁照抄）都没治住。
//     glm-4-flash-250414（文字）——正文完全对（"这道题你当时是怎么做的？从第一步开始说。"），
//       但 ```想说 围栏掉到 0/4。小模型一次只做得了一件事。
//   结论：**按钮这条不能赌模型。** 免费通道上按说不上就不出，学生面前只剩一个空输入框，
//   他很可能就此不说话了——这正是这个功能要防的事。
//   所以：模型给了就用模型的（更贴这道题），没给就用下面这份兜底（一定出得来）。
//
// 写法守着 v18 那四条死规矩：写学生的话、不向老师要东西、不写结论、一句不超过 20 字。
SR.CHIPS = {
  // 刚把题贴进来，还没说自己的做法
  open: [
    '我第一步就不知道从哪下手',
    '我大致有个想法，但说不清楚',
    '这题我读了两遍还是没看懂'
  ],
  // 他讲完了自己怎么做的
  said: [
    '我觉得中间有一步不太对',
    '我说完了，但心里没底',
    '我不知道问题出在哪一步'
  ],
  // 卡住、答不上来
  stuck: [
    '我算到这儿就不会了',
    '那个式子我忘了怎么处理',
    '我可能是符号搞错了'
  ],
  // 上一轮老师肯定了他自己说出来的那句
  got: [
    '原来是卡在这儿',
    '我懂了，但还想再讲一遍',
    '我下次会留意这一步'
  ],
  // 教师演示模式。★ 这一档和上面四档**不是一类东西**：上面是学生的话，这一档是
  //   老师对着画板说的话。原来演示模式也在出学生那几句——老师屏幕上摆着
  //   "我第一步就不知道从哪下手"，公开课和评审演示最容易在这儿露怯（e2e 里拍到的）。
  //   下面三条只用**画板确实做得到**的动作（三条都实测过）：立方体+旋转、切三维画球、
  //   数轴+动点。措辞照着 prompt-demo.js 里教模型的那套写法（说"要画什么"，不写命令）。
  //   ★ 只放三条、而且写短：`#chips` 是 flex-wrap 的，四条长句会折成两三行，
  //     把输入框往上顶掉一大截。别再加第四条——"擦掉重画"工具条上本来就有按钮。
  demo: [
    '画个正方体，让它转起来',
    '换成三维，再画个球',
    '切回平面，画条数轴加个动点'
  ]
};

// ★ 提示词里那段示范，是**给模型看形状的**，不是给它抄的。
//   可小模型就是会抄——2026-10-01 带图那一轮实测，glm-4.6v-flash 正文守得很好
//   （"答案是啥不重要。这道题你当时是怎么做的？"），三个按钮却一字不差搬了示范：
//     「我看它们在数轴上谁靠左谁靠右 / 我不确定，感觉差不多大 / 我不会比，以前就随便写的」
//   这是**另一道题**的话（比大小那题），摆在这道解方程题下面，学生点了等于自己说错话。
//   提示词那边不能删示范——删了模型连围栏都不写了（4/6 → 0/8，实测）。
//   所以只能在这一头挡：出口过滤。
//   ⚠ 提示词里每换一次示范，这里就得跟着换。test/probe_fence.cjs 的 EX 是同一份名单，
//     两边一起改，别只改一处（那边的数字就是靠这份名单才没骗人）。
SR.EXAMPLE_CHIPS = [
  '我看它们在数轴上谁靠左谁靠右', '我不确定，感觉差不多大', '我不会比，以前就随便写的',
  '我照着题目把条件都标上去了', '我大概知道该看哪儿，但说不清', '我卡住了，不知道下一步干什么',
  '我把 -2 标在 0 左边两格', '我标好了，但不确定对不对', '我画不出来，尺子找不到了'
];
// 抄了就整组作废（示范是按三句一组给的，命中一句基本就是整组搬）。
// 作废不是"留空"——chat.js 见它返回空，会落回下面的本地兜底，学生照样有得点。
//
// ★ 光比"整句一模一样"不够（2026-10-01 实测，DeepSeek 那 6 条里 5 条搬了示范）：
//   它抄的时候**总是改几个字**——
//     示范：我不确定，感觉差不多大      它写：我不太确定，感觉差不多
//     示范：我不会比，以前就随便写的    它写：我不会看，以前就随便写的
//   这些改法整句比对都漏掉。所以再加一道"六字雷同"：
//   把两边的标点空格全去掉，只要有一串连续六个字撞上，就按抄了处理。
//   （上面前两例撞上的是"感觉差不多"和"以前就随便写的"。）
//   ⚠ 宁可错杀：错杀的代价只是**换成下面那份本地兜底按钮**，学生照样有得点；
//     放过的代价是学生点一下就替自己说了一句提示词里的话，性质不一样。
//   ⚠ 提示词里每换一次示范，EXAMPLE_CHIPS 和这份 gram 表要一起重建（下面自动建）。
SR.normChip = function (s) {
  return String(s == null ? '' : s).replace(/[\s，。、,.!！?？…—·:：;；"'“”‘’()（）\[\]【】]/g, '');
};
SR.EXAMPLE_GRAMS = (function () {
  var set = {}, CH = 6;
  SR.EXAMPLE_CHIPS.forEach(function (c) {
    var n = SR.normChip(c);
    for (var i = 0; i + CH <= n.length; i++) set[n.slice(i, i + CH)] = 1;
  });
  return set;
})();
SR.filterCopiedChips = function (lines) {
  var ls = (lines || []).filter(function (s) { return String(s).trim(); });
  if (!ls.length) return [];
  for (var i = 0; i < ls.length; i++) {
    var s = String(ls[i]).trim();
    if (SR.EXAMPLE_CHIPS.indexOf(s) >= 0) return [];            // 一字不差
    var n = SR.normChip(s);
    for (var j = 0; j + 6 <= n.length; j++) {
      if (SR.EXAMPLE_GRAMS[n.slice(j, j + 6)]) return [];       // 六字雷同
    }
  }
  return ls;
};

// 挑哪一档。按"这段对话走到哪儿了"判，不按模型心情判。
//   opts: { demo 是不是教师演示模式, first 是不是学生第一轮,
//           lastUser 学生上一句, prevAssistant 老师上一句 }
SR.fallbackChips = function (opts) {
  opts = opts || {};
  // ★ 演示模式先分出去：老师不是学生，那几个台阶对他没意义
  //   （"我算到这儿就不会了"摆在老师屏幕上就是错的）。
  if (opts.demo) return SR.CHIPS.demo;
  var prev = String(opts.prevAssistant || '');
  // 走完第五台阶（肯定）之后，给"我懂了"这一类——这四个字是 v18 收尾那一档的原话
  if (/这类题的关键|说出来了|这一步做得对|就是这一步/.test(prev)) return SR.CHIPS.got;
  if (opts.first) return SR.CHIPS.open;
  var t = String(opts.lastUser || '').trim();
  // 短、且是"答不上来"的话 → 给台阶那一档
  if (t.length <= 20 && /不会|不知道|不懂|没思路|忘了|卡住|不会做|没听懂|想不起来|没想法/.test(t)) {
    return SR.CHIPS.stuck;
  }
  return SR.CHIPS.said;
};
