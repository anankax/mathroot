// ★ **纯前端读，不靠模型另外写一个档号。** 为什么不派给模型单独去写：
//   小模型一次只服从得了一件事（config.js 那段实测）。但它**不用多写一个字**——
//   提示词本来就把节标题规定成 `第 N 节 · 名字`，那一行是链子的一部分，
//   前端顺手从里面读出来就行。
//
// ★ 2026-10-02 换掉了原来那套**正则猜问句**的做法。旧版要判"模型这一轮问的是
//   复述还是追问"，写了一大串词表（/最没底|不对劲|最碍事|哪一步/ …），还得出特例：
//   老师的课题名里带个"哪一步"就能把进度条顶到第二档，还得再补一条"第一轮不许往下跳"。
//   现在节号是模型自己标出来的，**读一个数字，不用猜**。
//
// ★★ 2026-10-02 第二次改：节号不再限于 1–5，名字也不再是那五个。
//   这一版读的是**这一段回复里到底摆了哪些节**（可能不止一节：「整条」那轮就是好几节），
//   外加它第一轮报的"大概几步"。返回值：
//     { steps:[{n,name}], current, planCount, routeCount }
//   · steps     —— 这一段里真出现过 `第 N 节 · 名字` 的那些节，按 n 升序、n 去重。
//   · current   —— 停在第几节（取最大的那个 n）。0 = 读不出来。
//   · planCount —— 它说的"大概几步"。0 = 没说／没读出来。只用来画灰格（预排），
//                  **不参与判档**：计划是预测，预测会漂。
//   · routeCount—— 第一轮那"几路"数出来**几条**（按路号去重，见下面 RE_ROUTE_C 那段）。只当指标打印，不驱动界面。
//
// ★ 分隔符 `·`（含 ・.:：）是**必须的**。节号放开到任意数字之后，
//   正文里"第 3 节车厢""第二节课"这类会误判；而提示词本来就强制 `第 N 节 · 名字`，
//   要求分隔符零成本，还顺带挡住"我打算第 1 节先让他复述"这种计划描述。
//
// ★ 纯函数，不碰 DOM——这样 test/probe_plan.cjs 能在 node 里直接拿它跑手写的假回复，
//   把边角（节号丢了／名字乱起／整条被截断／报了几路）都量一遍，不花额度。
// ★★ 2026-10-02：链子的单位从「节」改成「环节」。
//   **解析器先放宽、提示词后改**——模型这两周还会写「第 3 节 · 名字」，台阶条得照样工作，
//   所以下面几条正则**两套都认**；等线上确认模型换过来了再收窄（不然就是自己把桥拆了）。
//   ⚠⚠ **绝不能全局替换「节」**：这个字在本仓库里还有另外两个意思——
//     ① **课本章节**（js/textbook.js 里一百多处、js/resources.js 的字段 `r.节`）；
//     ② **字节**（js/docx.js、js/produce.js 里十来处）。
//   动到的只有下面这几条正则和本机文案，别的一律不碰。
var UNIT = '(?:个?\\s*环节|节)';
var RE_STEP = new RegExp('第\\s*([0-9]+)\\s*' + UNIT + '\\s*[·・.:：]\\s*([^\\n]*)', 'g');
// 数字：阿拉伯或中文。中文那套只认到"十"，够用了——报步数不会超过十。
// ★ "两"必须收进来：真 glm 报计划时写的是「打算先走第一路，**大概两节**」，
//   而中文里"两个"比"二节"自然得多——不收它，"两节"就永远读不出，灰格永远不出现。
//   （test/probe_chain.cjs 走全流程时当场抓到的，不是想出来的。）
var NUM_W = '(?:[0-9]+|[一二两三四五六七八九十])';
// "大概 4 节" / "大约 3～4 节" / "先走四步" —— 只认前面带引导词的那些。
// ★★ 量词必须**步、节都认**：提示词里那句要求写的是「再说你打算先走哪一路、大概**几节**」，
//   模型照它答的就是"大概 4 节"。第一版只写了 `步`，于是计划永远解析不出来、
//   灰格永远不出现——**提示词问的是节，尺子量的却是步**（写 test/probe_plan.cjs 时当场抓到的）。
// ★ 故意**不做**成"任何 `N 步` 都算"：正文里"下一步""第一步"太多了，
//   那样一定会把别的东西认成计划。认不出来就不画灰格，代价最小。
//   （引导词那一道闸正好挡住 `第 4 节 · 名字` —— "第"不在词表里。）
// ★★ 引导词和数字中间还得容下几个字：真 glm 写的是「大概**需要**三节」，
//   中间那个"需要"一挡就整句读不出（同一条采样里它把计划写出来了，尺子却报"没报"）。
//   顺带容下 markdown 的 `**`（`大概需要**三节**` 也出现过）——所以分隔用 `[\s*]*` 不用 `\s*`。
var RE_PLAN = new RegExp('(?:大概|大约|差不多|预计|一共|总共|得走|要走|先走|走)' +
                         '(?:需要|要|得|用|花)?[\\s*]*(' + NUM_W + ')' +
                         '[\\s*]*(?:[～~\\-—至到]\\s*' + NUM_W + '\\s*)?(?:步|' + UNIT + ')');
// 路数：认 ①②③ 那种圈号，也认"第一种""第 2 路"。★ 阿拉伯数字也收——
// 模型嘴上说"先走哪一路"，落笔常常写的是「第 1 路」。只当指标打印，不驱动界面。
//
// ★★ 记的是**去重后的路数**，不是命中次数。写 test/probe_plan.cjs 时当场抓到的：
//   一轮里"① ② ③"列了三路，末尾还有一句"先走第 1 路"——按次数数出来是 4 条，
//   而老师看到的是 3 条。**尺子比它宣称的东西宽，报出来的就是假警报**
//   （记忆里那条"检测脚本的数字不是它宣称的那件事"）。
//   两族写法（圈号／第 N 种·路）归到同一个号池里，同一个号只算一次。
var CIRC_ROUTE = { '①': 1, '②': 2, '③': 3, '④': 4, '⑤': 5, '⑥': 6 };
var RE_ROUTE_C = /[①②③④⑤⑥]/g;
var RE_ROUTE_N = new RegExp('第\\s*(' + NUM_W + ')\\s*[种路]', 'g');
// ★★ 还有一族写法不能不认：**行首的普通编号** `1. 学生大概会说…`。
//   2026-10-02 实测（这是拿真 glm 跑出来的，不是想出来的）：它给的两条路写成
//   `1.` `2.`，上面两条一条都没认出来，报出去的是"没给出几路"——
//   **尺子比它宣称的东西窄**，报出来的是假警报（同族教训：检测脚本的数字不是它宣称的那件事）。
//   只认**行首**（`^\s*`）：正文里 `第 1 节 · 名字` 那一行、句中的"3 个条件"都不会撞上。
//   ⚠ 还得把**末尾那句计划**排掉：实测那份回复是 `1. …路 / 2. …路 / 3. 我打算先走第一路，大概 3 节。`
//     ——第三行也是行首编号，可它是**计划不是路**，不排掉就多报一条（把 2 条说成 3 条，
//     回到"尺子比它宣称的宽"，一样是假警报）。
var RE_ROUTE_L = /^\s*([0-9]{1,2})\s*[.、)）]\s*([^\n]*)$/gm;
// ★★ 第四族：**光秃秃一行一句「学生大概会说：…」，前头什么标号都没有**。
//   2026-10-02 采样 8 次里出现了 1 次（就是这一族当时没被认，报的是"没给出几路"）：
//     `学生大概会说：点 B 在点 A 的左边还是右边我不知道，所以 x 可能是 -7 或者 3。`
//     ×5 行，每行一条路。
//   ⚠ 前头**只许是项目符号，不许是编号**（`1. 学生大概会说：…` 归上面那一族数）——
//     不然同一条路会被两族各数一次，数字就虚高了。
var RE_ROUTE_B = /^\s*(?:[-*·•]\s*)?学生大概会说[：:]/;
// 「这句不是一条路，是在交代计划」：`我打算先走第 1 路，大概 3 节。`
// ★ 三个族**都要过这道闸**，不能只挡行首编号那一族：模型写「先走第 1 路」时用的是
//   **第N路**这一族的话面（第一路／第 1 路），闸只设在 L 上面，它照样会从 N 那一族漏进来
//   —— 于是"两条路"被数成 1（第一路被当成了路 1，两条 `1.` `2.` 反倒没被数）。
//   所以判据不是"它写在哪儿"，是**这一行在说的话是哪种话**：看那一行整行。
// ★ 单位那一档跟上面 RE_PLAN 共用 UNIT（2026-10-02 起「节」和「环节」都认）。
var RE_PLAN_ISH = new RegExp('打算|先走|大概\\s*(?:[0-9]+|[一二三四五六七八九十])\\s*(?:步|' + UNIT + ')');
// 那三行的词面里，**只有这两个**能当"这不是路"的证据。
// ⚠ 「学生大概会说」**不能进这张表**：路那条写的就是学生的话，真 glm 的回复
//   （test/probe_plan.cjs 里那条 `行首普通编号`）两条路都长成 `1. 学生大概会说：…`。
//   把它当噪声排掉，尺子就又把两条路数成 0 了 —— 治假阳性治出了假阴性，一样坏。
//   「你接这句」「这么接的道理」不一样：**它们永远不会是一条错法的内容**。
var RE_LINENAME_ISH = /你接这句|这么接的道理/;

// 某个下标落在哪**一句**上（路由器三个族共用）。
// ★ 口径是"句"不是"行"：路和计划**可以挤在同一行**里
//   （`学生可能有两种错法：①…②…。我打算先走第 1 路，大概 3 节。`）。
//   按行判的话，这一整行都算"计划"，两条路一起被抹掉；
//   按句判，只抹掉"我打算…"那一句，两条路各在各的句子里，留得住。
function sentAt(t, idx) {
  var B = /[。！？!?\n]/;
  var a = idx, b = idx;
  while (a > 0 && !B.test(t.charAt(a - 1))) a--;
  while (b < t.length && !B.test(t.charAt(b))) b++;
  return t.slice(a, b);
}

function toNum(s) {
  s = String(s || '');
  if (/^[0-9]+$/.test(s)) return parseInt(s, 10);
  var D = { 一: 1, 二: 2, 两: 2, 三: 3, 四: 4, 五: 5, 六: 6, 七: 7, 八: 8, 九: 9, 十: 10 };
  if (s.length === 1) return D[s] || 0;
  if (s.charAt(0) === '十') return 10 + (D[s.charAt(1)] || 0);      // 十一、十二
  return D[s.charAt(0)] || 0;                                        // 二十一 → 2（够用）
}
// 名字是从行尾整段截下来的，顺手把它身上可能带的 markdown 壳剥掉：
// 模型偶尔会写成 `**第 1 节 · 名字**` 或者带反引号。剥干净了按钮上才不会出现星号。
function cleanName(s) {
  return String(s || '').replace(/^[\s*#`>]+/, '').replace(/[\s*#`]+$/, '').trim();
}

SR.parseChain = function (text) {
  var t = String(text || '');
  var out = { steps: [], current: 0, planCount: 0, routeCount: 0 };
  if (!t) return out;

  var seen = {}, m;
  RE_STEP.lastIndex = 0;
  while ((m = RE_STEP.exec(t)) !== null) {
    var n = parseInt(m[1], 10);
    if (!n || seen[n]) continue;             // 同一节写了两遍（标题 + 回指）只算一次
    seen[n] = 1;
    out.steps.push({ n: n, name: cleanName(m[2]) || ('第 ' + n + ' 节') });
  }
  out.steps.sort(function (a, b) { return a.n - b.n; });
  if (out.steps.length) out.current = out.steps[out.steps.length - 1].n;

  var p = RE_PLAN.exec(t);
  if (p) out.planCount = toNum(p[1]);

  // ★★ 路数和节数**各算各的，互不干涉**。
  //   这里原来挂过一条闸：「摆了节的这一轮，路数一律记 0」。2026-10-02 **拆了**——
  //   它在采样里当场撒了一次谎：真 glm 有一轮**既报了 3 条路、又顺手摆了 3 节**，
  //   闸一挡，报出去的是"没给出几路"。可原文里路明明在，尺子把它抹了。
  //   路数和节数是**两个事实**，各自是什么就报什么；"这一轮不合规矩"该由
  //   判据那一头去说（probe 自己会同时报"给了几路"和"多摆了链子"），不该由尺子替它下结论。
  //   ⚠ 去掉这条闸之后，链子那轮若把三行各自编上号，会被数出 1 条"路"——所以下面
  //     两族各加了"至少两条"的门槛，见那两处的注释。
  // ★★ 数路这件事**只有一份**，就是下面那个 routesOf。这儿只问它有几条。
  //   （原来这一整块就长在这个函数里，"几条路"和"每条路说了什么"分不开，
  //   于是导图那边只能另写一套正则去认路的内容——那就是两个真源。）
  out.routeCount = routesOf(t, out.steps.length).length;

  return out;
};

// ============================================================
//  这一轮给了几条路、每条路说了什么
// ============================================================
// ★ 从 parseChain 里**搬出来**的（2026-10-02，做思维导图时）。原样搬家，判定一个字没改：
//   parseChain 仍然拿它数 routeCount，所以"几路"这个读数的口径没动一根汗毛。
//   它比原来多交出来的只有一件事：**每条路的内容**——原来只数个数，内容全扔了，
//   而思维导图要画的正是这个内容。
//
// 返回**有序数组** `[{ key, label, text }, …]`：
//   · key   号池里的号。①② 那两族共用一个池（'1' '2' …），光秃秃那一族另起一套
//           （'b1' 'b2'）——撞上就等于两条路被当成一条，数字会虚低（原注释里那条）。
//   · label 模型自己写的那个标号（'①' / '第 2 路' / '1.' / '学生说'），只作旁证。
//   · text  **学生那句话**。四条族抄下来的原话里，前缀（`学生大概会说：`、
//           标号、破折号）一律剥掉——导图上要画的是**孩子在说的话**，
//           不是"学生大概会说"这六个字。
function words(s) {
  return String(s == null ? '' : s)
    .replace(/^[\s\-—–－·•*>]+/, '')
    .replace(/^学生[^：:，,。]{0,8}说[：:，,]?\s*/, '')
    .replace(/^[\s：:，,。.、)）\]]+/, '')
    .replace(/[\s；;，,]+$/, '')          // 尾巴上那个分号是切出来的，不是学生说的
    .replace(/\s+/g, ' ')
    .trim();
}
// 命中处往后，**这一条路**说了什么。
// ★ 只取同一行：这几族路都是一条一行写下来的（实测）。
// ★ 撞到下一个路标就停：模型常把两条路挤在同一行里
//   （`学生可能有两种错法：①…②…。`）。不切的话第 1 条路会把第 2 条整个吞进去，
//   导图上就成了同一句话画两遍。
var RE_MARK = /[①②③④⑤⑥]|第\s*(?:[0-9]+|[一二两三四五六七八九十])\s*[种路]/;
function tail(t, from) {
  var e = t.indexOf('\n', from);
  if (e < 0) e = t.length;
  var s = t.slice(from, e);
  var m = s.search(RE_MARK);
  if (m >= 0) s = s.slice(0, m);
  // ★ 尾巴上常粘着"我打算先走第 1 路，大概 3 节"——那是**交代计划**，不是这条错法。
  //   不切的话最后一条路会把半句计划吞进去（实测：`他把 -7 当成 7 了。我打算先走`）。
  //   判定**复用 RE_PLAN_ISH**，跟"这一句算不算一条路"是同一把尺子，不另写一套。
  var B = /[。！？!?；;]/;
  for (var i = 0; i < s.length; i++) {
    if (!B.test(s.charAt(i))) continue;
    var rest = s.slice(i + 1);
    if (RE_PLAN_ISH.test(rest.split(B)[0] || '')) { s = s.slice(0, i + 1); break; }
  }
  return s;
}
// 光看这一段里有几节（≥1 的那一族要用它）。跟 parseChain 里那段同样的去重口径。
function stepCount(t) {
  var seen = {}, m, n = 0;
  RE_STEP.lastIndex = 0;
  while ((m = RE_STEP.exec(t)) !== null) {
    var k = parseInt(m[1], 10);
    if (!k || seen[k]) continue;
    seen[k] = 1; n++;
  }
  return n;
}

function routesOf(t, nSteps) {
  var list = [], seen = {}, rm;
  function add(key, label, raw) {
    if (seen[key]) return;                 // 同一条路提了两遍，只算一次（也保留**第一次**的说法）
    seen[key] = 1;
    list.push({ key: key, label: label, text: words(raw) });
  }

  RE_ROUTE_C.lastIndex = 0;
  while ((rm = RE_ROUTE_C.exec(t)) !== null) {
    if (RE_PLAN_ISH.test(sentAt(t, rm.index))) continue;   // 计划那句里的路号是在**指路**，不是在开一条新路
    add(String(CIRC_ROUTE[rm[0]]), rm[0], tail(t, rm.index + rm[0].length));
  }
  RE_ROUTE_N.lastIndex = 0;
  while ((rm = RE_ROUTE_N.exec(t)) !== null) {
    var rn = toNum(rm[1]);
    if (!rn) continue;
    if (RE_PLAN_ISH.test(sentAt(t, rm.index))) continue;
    add(String(rn), '第 ' + rn + ' 路', tail(t, rm.index + rm[0].length));
  }

  // 行首编号那一族：**只有前面两类一条都没认出来才用它**。
  // ★ 为什么留着这条闸（2026-10-02 试过拆掉，又装回来了）：模型讲路时**嘴上说的是路**
  //   （①②③／"第 1 路"），落笔才退化成普通编号。两族都在时，"路"那两族是**明确的说法**，
  //   该让它赢。拆掉闸之后，有一轮把 4 个编号（其中两条只是铺垫、最后才收成两条路）
  //   全算成路，报出 4 —— 那是**比它宣称的宽**，跟少报一样是假警报。
  //   ⚠ 闸只管"谁来数"，不管"算不算路"：前两类数出来的号跟这一族的号是同一个号池，
  //     同一条路只会算一次。
  var lh = [];
  if (!list.length) {
    RE_ROUTE_L.lastIndex = 0;
    while ((rm = RE_ROUTE_L.exec(t)) !== null) {
      if (RE_PLAN_ISH.test(rm[2])) continue;      // `3. 我打算先走第一路，大概 3 节。` —— 这是计划，不是一条路
      if (RE_LINENAME_ISH.test(rm[2])) continue;  // `2. 你接这句：…` —— 这是链子三行自己的编号
      var ln = toNum(rm[1]);
      if (ln) lh.push({ n: ln, s: rm[2] });
    }
  }
  // ★ 至少两条编号才算"几路"。链子那一轮把三行编上号时，只有第 1 行（`1. 学生大概会说：…`）
  //   过关（另两行带 `你接这句`／`这么接的道理`，被上面挡掉），一条孤零零的编号不是路清单。
  //   "几路"本来就是**两到四条**——一条算不上。
  if (lh.length >= 2) lh.forEach(function (x) { add(String(x.n), x.n + '.', x.s); });

  // 光秃秃那一族。**另起一套键**（`b1` `b2`…），免得跟上面那三族的号（1、2、3）撞上
  // ——撞上就等于两条路被当成一条，数字又虚低了。
  // ⚠ 两处闸，都是拿真回复量出来才加上的：
  //   ① **前面三族一个都没认出来才用它**。2026-10-02 实测：模型把路写成
  //      `1. 第一步错误：…` + 每条底下再挂一行 `- 学生大概会说：…` 时，
  //      编号族数出 4 条、这一族又数出 4 条，报出去的是 **8 路**——同一批路被数了两遍。
  //      它是"连编号都没有"那种形状的兜底，编号族有话说时就轮不到它。
  //   ② **至少两行才算**。链子那一轮也有一行 `学生大概会说：…`；**节号写成汉字
  //      "第一节"的那一轮 steps 是 0**，没有这道门槛的话，一行就被数成"一条路"
  //      （报 1 路，真值 0）。两行以上才可能是路清单。
  //   ③ **摆了节的这一轮，这一族整个不数**。（另两族不受这条管——见上面那段注释：
  //      有一轮既报了路又摆了节，编号族把它报了 3 条路，那是对的。）
  //      理由很实在：`学生大概会说：…` **正是链子那三行的第一行**，一条三节的链子
  //      摆完就有三行，不拦的话这一族会把三行数成"三路"。它只认得形状，认不出含义，
  //      所以只在"这轮压根没摆节"时才敢说话。
  if (!nSteps && !list.length) {
    var bare = [];
    t.split('\n').forEach(function (l) {
      if (!RE_ROUTE_B.test(l)) return;
      if (RE_PLAN_ISH.test(l)) return;
      bare.push(l);
    });
    if (bare.length >= 2) bare.forEach(function (l, k) { add('b' + (k + 1), '学生说', l); });
  }
  return list;
}

// 这一段里给了几条路、每条说了什么。给思维导图用的那条口子。
SR.parseRoutes = function (text) {
  var t = String(text || '');
  return t ? routesOf(t, stepCount(t)) : [];
};

// ★ 数字怎么认（'3' / '三' / '两'）——导图要判断"它选了第几路"，
//   而那个判断跟上面几族路用的是**同一本数字表**。露出来，别在别处再抄一本。
SR.numOf = toNum;

// ============================================================
//  链子每节底下的那三行
// ============================================================
// 提示词规定一节长这样：`第 N 节 · 名字` 开一行，底下三行——
//   学生大概会说：…
//   你接这句：…
//   这么接的道理：…
// 思维导图上每个环节的节点里要挂的就是这三行。**纯函数**，node 里能测。
//
// ★ 为什么要单独一个函数、不塞进 parseChain：parseChain 只认节号和名字，
//   它连"这一节的正文有多长"都不管；而导图要的是**这一节说了什么**。
//   两件事合在一个返回里，就得把 parseChain 的返回值改大，动的是台阶条那条线
//   （chat.js 和两把尺子都在读它）。分开，谁都不动谁。
//
// 返回 `{ 1: {said, you, why}, 3: {...} }`——按节号索引。
// 读不出来就是空串，**绝不替它编**：节点上宁可是空的，也不能长出模型没说过的话。
SR.parseStepBody = function (text) {
  var t = String(text || ''), out = {};
  var heads = [], m;
  RE_STEP.lastIndex = 0;
  while ((m = RE_STEP.exec(t)) !== null) heads.push({ n: parseInt(m[1], 10), start: m.index, end: RE_STEP.lastIndex });
  for (var i = 0; i < heads.length; i++) {
    var h = heads[i];
    if (!h.n || out[h.n]) continue;
    var body = t.slice(h.end, i + 1 < heads.length ? heads[i + 1].start : t.length);
    var o = { said: '', you: '', why: '' }, cur = '';
    body.split('\n').forEach(function (raw) {
      var l = raw.replace(/^[\s\-—–*·•>]+/, '').trim();
      if (!l) return;
      var mm;
      if ((mm = /^学生[^：:，,。]{0,8}说[：:]\s*(.*)$/.exec(l))) { o.said = mm[1].trim(); cur = 'said'; return; }
      if ((mm = /^你接这句[：:]\s*(.*)$/.exec(l))) { o.you = mm[1].trim(); cur = 'you'; return; }
      if ((mm = /^这么接的道理[：:]\s*(.*)$/.exec(l))) { o.why = mm[1].trim(); cur = 'why'; return; }
      // 换行接下去的续行：接到刚才那一栏上。★ 模型把一句话折成两行是常事，
      //   丢掉续行等于把话腰斩（老师看到的是半句话）。
      if (cur) o[cur] = (o[cur] ? o[cur] + ' ' : '') + l;
    });
    out[h.n] = o;
  }
  // ⚠ 上面按 heads[i+1].start 取段——所以 heads 里每一项都得带上 start。
  return out;
};

// 这一段文本里到底摆过链子没有。★ api.js 用它判"这条对话还一次都没摆过"，
// 好决定要不要挂第一轮那块「几路」的附注（见 api.js 的 buildSystem）。
// 判定口径跟 parseChain 共用同一套，别在别处另写一个正则——那正是"改一处忘一处"的老毛病。
SR.hasChain = function (text) {
  return SR.parseChain(text).steps.length > 0;
};

// 摆到第几节。★ 保留这个名字是因为 chat.js 和探针都在用；现在它就是 parseChain 的一个读数。
// ★ 认不出来时返回 0 = **原地不动**（chat.js 见 0 会 keep 住当前那一节）。
//   **绝不能随手退回 1**：模型偶尔少写一个节号，进度条整个掉回起点，
//   老师会以为是自己的操作把它弄回去了。
// ★ 第一轮也不再返回 1 了。第一轮给的是"几路"，链子还没开始摆，
//   点亮一根"第 1 节"等于替它编了一步它没说过的（见 js/prompt-prep.js）。
SR.inferStep = function (opts) {
  opts = opts || {};
  if (!opts.prevAssistant) return 0;
  return SR.parseChain(opts.prevAssistant).current;
};

// ============================================================
//  台阶条的**状态**（纯函数；chat.js 只负责照它画）
// ============================================================
// ★ 状态就三个数，`state = { slots:[{n,name}], plan, now }`：
//     slots —— 已经摆出来的节
//     plan  —— 它第一轮报的"大概几节"，只用来在末尾补几格**灰格**（预排）
//     now   —— 停在第几节
// ★★ 两条铁律，**都写成代码放在这儿、不放进 chat.js**，就是为了让
//   test/probe_chain.cjs 能在 node 里拿假回复直接量（纯函数用假数据量，不花额度）：
//     ① **只增不减**：报了 4 节却走到 6 节 → 槽位长到 6；报了 5 节只走到 3 节 →
//        那三格照样在。**绝不把已经摆出来的节藏起来**——老师看得见的东西不能说没就没。
//     ② 计划只认**第一次**报的那个数：之后哪一轮随口说"还有两步"，不算改计划。
//   ⚠ 灰格是**预排、不是事实**：plan 只影响"末尾多画几格灰的"，**绝不参与判档**。
//     `now` 永远只由模型真写出来的 `第 N 节` 决定（见上面 SR.inferStep）——
//     计划是预测，预测会漂；让预测去驱动"老师以为自己在第几节"，
//     就是在替模型编它没说过的进度。
SR.chainState = function () { return { slots: [], plan: 0, now: 0 }; };

SR.absorbChain = function (state, text) {
  if (!state) state = SR.chainState();
  if (!state.slots) state.slots = [];
  if (!SR.parseChain) return state;
  var p = SR.parseChain(text);
  if (!state.plan && p.planCount) state.plan = p.planCount;
  for (var i = 0; i < p.steps.length; i++) {
    var s = p.steps[i], has = false;
    for (var j = 0; j < state.slots.length; j++) if (state.slots[j].n === s.n) { has = true; break; }
    if (!has) state.slots.push({ n: s.n, name: s.name });
  }
  state.slots.sort(function (a, b) { return a.n - b.n; });
  if (state.slots.length > state.plan) state.plan = state.slots.length;
  return state;
};

// 挑哪一档按钮。按工位分派。
//   opts: { work 工位 id, first 是不是第一轮,
//           lastUser 老师刚说的话, prevAssistant 数根上一句 }
SR.fallbackChips = function (opts) {
  opts = opts || {};
  var work = opts.work || SR.DEFAULT_WORK;
  if (work === 'draw') return SR.CHIPS.draw;
  if (work === 'vary') return SR.CHIPS.vary;
  if (work === 'material') return SR.CHIPS.material;
  if (work === 'grade') return SR.CHIPS.grade;
  // 讲评第一轮：数根刚把卷子上的题号列完，老师该挑讲哪一道了。
  // 之后就回到链子（他挑定一道、链子一开始，动作就跟备课一模一样）。
  if (work === 'review' && opts.first) return SR.CHIPS.review;
  if (work === 'prep' || work === 'review') return SR.CHIPS.chain;
  // ★ 走到这一行的只剩"没见过的工位 id"。给链子那套是**故意的**：
  //   五个工位里有两个（备课／讲评）本来就是链子，是这里的大多数。
  //   ⚠ 但别再让**新工位**落到这儿——2026-10-02 出材料就是这么被漏掉的。
  return SR.CHIPS.chain;
};
