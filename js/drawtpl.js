// 作图模板 —— 老师填几个空，**命令骨架由这儿算好**，模型只负责讲人话、按老师的话微调。
//
// ★★ 为什么要有这个文件（孔老师 2026-10-05 那句话是它的出生证明）：
//    「最好是给一个可填写的模板给客户，要让大模型画图画的准，画的漂亮，画的美观」
//    「你也得检查你的命令，看看有没有和苏科版教材不契合的地方，定义都应该根据课本来」
//
//   背景是实测出来的：免费通道那颗小模型画「角 aob」，三遍里两遍把 `角(A,B,C)` 的
//   三个字母写歪（顶点写到第一个字母上／两条边绕反了方向），引擎就吐 302° 的优角。
//   病根**不在模型会不会数学**——它知道角有顶点有两条边；病根是「角」这个图形
//   在提示词里**没有一个现成的样子**，它只能拿最顺手的三角形那套往上套。
//   提示词补一段能救回来大半（补完之后第一遍就画对了），**可剩下的那一小半是随机的**：
//   小模型每次都可能换个写法。**随机的东西不能靠讲道理治好，只能靠不给它机会。**
//
// ★★ 所以分工是这样的（孔老师当场拍板的那一档，原话「丙」）：
//     · **骨架是算出来的，不是模型写的**。顶点在哪个字母上、两点谁逆时针谁顺时针、
//       余弦该乘多少——这些全在下面 `骨架(f)` 里用真的三角函数算出来，
//       模型**没有机会**把字母写歪，因为那三个字母是拼好递给它的。
//     · **但模型没被捆住**：骨架是当"参考"给它的（见 `取骨架()` 拼出来那段话），
//       老师往下说「把这个角变成直角」「再加一条角平分线」，模型照旧自由发挥。
//       它改的是"加什么"，不是"顶点在哪儿"。
//     · **不在模板里的图一点没被卡**（三角形内切圆、动点轨迹、立体截面……）：
//       那些照旧走老师随口一句话那条老路，一个字都没动。
//
// ★★ 判据是**跟课本对齐**，不是我自己觉得对：
//     · 三角形那一档写「**等边**三角形」不写「正三角形」——苏科版正文用的就是"等边"。
//     · 四边形那一档是平行四边形／矩形／菱形／正方形，跟苏科版八下的叫法一致。
//     · 「垂直平分线」给正式名，「中垂线」是简称，两个都收（课本正文两个都用过）。
//     · 角的记号写成 ∠AOB 而不是「角AOB」——课本上就是这么印的。
//   ⚠ `js/textbook.js` 里**没有**角的定义那一段原文（那份只收了若干节的正文），
//     所以这一档的措辞是从苏科版的行文习惯来的，**不是我核过的原文**。别当物证用。
//
// ★★ 还有一件事它顺手就治了：**角度是精确的**。
//     骨架里 B 点是 `(3cos60°, 3sin60°)` 真算出来的 (1.5, 2.598)，
//     所以画出来板上量到的是 60.00°，不是 59.8 也不是 61.1。
//     老师要拿图去讲课、去印学案，差半度就是错的。
//     （对照：模型自己挑坐标那几遍，量出来 60.02°——它挑 (1.5,2.6) 是手感的。）
