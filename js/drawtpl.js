  // ★ 为什么要收这个：`(1.5, 2.598076211353316)` 那种一长串小数写进命令里
  //   GeoGebra 照收，可老师点开"代数区"一看就是一串垃圾。留三位够用（0.001 的误差
  //   在初中图上小到量不出来），而且 3、-2 这种整数出来还是 `3`、`-2`。
  function 数(x) {
    var v = Number(x);
    if (!isFinite(v)) return '0';
    v = Math.round(v * 1000) / 1000;
    if (v === 0) v = 0;                       // 把 -0 摁成 0
    return String(v);
  }
  // 从输入框里抠一个数出来（老师可能只填了空白，也可能填了中文）
  function 抠数(s, 兜底) {
    var v = parseFloat(String(s == null ? '' : s).replace(/[^\d.\-]/g, ''));
    return isFinite(v) ? v : 兜底;
  }
  // 字母：只留一个合法的 GeoGebra 名字。★ 老师填了中文/空格/标点都在这儿收拾干净，
  //   不然拼出来的命令是一条废的（而且板子那边只会静默记一笔"没落地"）。
  function 字母(s, 兜底) {
    var t = String(s == null ? '' : s).replace(/[^A-Za-z0-9_]/g, '');
    return t || 兜底;
  }
  // 点坐标那一格：「-2, 3」→ [-2, 3]
  function 抠一串数(s) {
    return String(s == null ? '' : s).split(/[,，、\s]+/)
      .map(function (x) { return parseFloat(x) })
      .filter(function (x) { return isFinite(x) });
  }

