// 「数根」的收敛保护 —— **改到第几轮还不成，就别再在这张图上挪一点改一点了。**
//
// ============================================================
// 借自哪儿（README 的「借鉴与出处」那张表要补一行）
// ============================================================
// · GeoChat（github.com/tiwe0/GeoChat，Apache-2.0）里
//   `backend/src/agent/agent-tool-orchestrator.ts` 的 `nativeConvergenceInstruction`：
//   它数"画了一笔、又验了一回"跑了几轮。跑到 4 轮，往下一轮的系统提示里塞一句
//   「【收敛提醒】已经历多轮写入与验证但任务仍未完成。再次写入前，必须从原始构造
//     重新检查数学不变量和依赖图；不要只靠继续调整符号或角度推进。」
//   到 6 轮下死命令：「最多再执行一次最终修正，随后立即验证…若不变量仍不成立，
//     明确说明限制，不要开启新一轮修补。」
// · 它 `builtin-skills/mathematical-animation-design/SKILL.md` 第 13 条是同一件事
//   在动画上的说法：连续两次违反同一个不变量就停手，「记录失败不变量和受影响的
//   依赖子图，回滚到最近正确关键状态后重建该子图。**不要把改样式或放慢动画当作
//   语义修复。**」
//
// **借的是那个轴，不是它的代码——一行代码都没搬。**
//
// ============================================================
// 为什么不能照搬，数根这一版是怎么改的口径
// ============================================================
// GeoChat 数得准，是因为它有**显式的验证工具**：模型写完调一次 inspect，一次
// "写入→验证"就是一个 cycle，它返回的 ok 是硬信号。数根没有这一步——画图工位
// 是"一句话进去、一段带围栏的话出来"，模型不会自己回头验。
//
// 所以数根**数不出 cycle，只能数轮**。而"一轮"在数根里有一个现成的、准的边界：
// **老师发一句话**（chat.js 的 `submit`）。
//
// 一轮里只要有一段画没落地，这一轮就记坏。落没落地不靠猜 —— board.js 的 `收尾`
// 本来就在算这件事（`failedNow` 悬空 / 空壳 / 哑），状态条上那句
// 「这一段里有 N 条画板没认」就是它。这里只是把那个判断**再借出来数一遍**。
//
// ⚠ 三条讲究（都有具体理由，别改）：
//
//   ① **冻图那一趟不算。** `收尾` 也会在 `offscreenJob` 借板截图时跑，可那一遍画
//      不是给老师看的，画坏了也不该记在模型头上。用 board.js 里现成的 `借板中`
//      挡住（见下面 `记坏` 那处的调用点）。
//
//   ② **清空不归零。** 老师的清空、模型自己写的 `#清空`，都**不许**把连败清零——
//      因为保护那句给的出路恰恰是"从头重画一版"，而重画的第一条就是 `#清空`。
//      在这儿清零 = 这道闸一开口就把自己关了。真正的清零只有一条路：
//      **下一轮画成了**（`翻篇` 里 `本轮坏` 是空的时候）。
//
//   ③ **`翻篇` 必须在 buildSystem 之前跑。** 它结算的是**上一轮**，而 `note()`
//      读的就是结算后的数。两件事都在 submit 这一趟里发生，顺序反了就会少算一轮。
//      （调用点写在 chat.js 的 submit 里 `busy = true` 旁边，那儿是"这句话真要发了"。）
//
// ============================================================
window.SR = window.SR || {};
(function () {
  var 连败 = 0;        // 连着几轮"画了但没落地"
  var 本轮坏 = false;  // 这一轮里，有没有哪一段画没落地

  // ------------------------------------------------------------
  //  板子账（2026-10-06）
  // ------------------------------------------------------------
  // 来路：孔老师贴的那段真对话——他让模型画长方体，模型先答「我无法直接操作
  // GeoGebra」，接着说了一句「**好的，我已经画好了长方体 ABCD-EFGH**」，而那一刻
  // 板子上是空的。它不是在撒谎，是**它真的不知道**：数根是一发一收，模型写完就交卷，
  // 板子上出了什么事（哪几条没落地、画出来是个什么）它一概收不到。
  // board.js 的 `收尾` 其实**每条都算出来了**（`段` 那几句话），可它只说给老师看
  // （走 log／状态条），一个字都没回到下一轮的提示词里。
  //
  // 所以这里只是给那几句话开一条回头的路：`收尾` 记账 → `翻篇` 定稿 → `buildSystem` 取走。
  // 一行判断都不新造，**贴的就是状态条上那几句原话**——两处口径不一样的话，
  // 老师看见的和模型看见的就会打架，那比都不说还坏。
  //
  // ⚠ 为什么账要分"这一轮"和"上一轮"两份：`翻篇` 是在**老师发下一句**的那一刻跑
  //   （chat.js 的 submit，`busy = true` 旁边），而 `buildSystem` 就在它**后面**。
  //   只留一份的话，翻篇清掉、buildSystem 立刻读，读到的永远是空的。
  //   顺序是：收尾写进 `账` → 翻篇把 `账` 挪成 `上轮账` 并清空 `账` → buildSystem 取走 `上轮账`。
  var 账 = null;       // 这一轮攒着的（一批一次，可能攒好几批）
  var 上轮账 = null;   // 上一轮结算下来的，等 buildSystem 取走**一次**

  // 线划在 2 和 3。为什么不是 GeoChat 的 4 和 6：它那边一个 cycle 是一次工具调用
  // （秒级），数根这边一轮是**一次完整的模型往返**（十几秒起，还要老师读完）。
  // 同一根尺子换个单位，刻度就得跟着换——照抄 4/6 等于让老师先烦四轮。
  var 提醒线 = 2;
  var 保护线 = 3;

  // 一段画没落地。由 board.js 的 `收尾` 在**判定之后**调（判干净的那一支不调）。
  function 记坏() { 本轮坏 = true; }

  // 一批画完了、判完了，把结论记下来。由 board.js 的 `收尾` 在**判完之后**调。
  //   o = { 段: [给老师看的那几句话], 命令: 这一批发出去几条 }
  // ⚠ 攒着不覆盖：一轮里可能有好几段 ```ggb（模型爱分几块写），每段都会喊一次 收尾。
  //   后一段把前一段顶掉的话，前一段"没落地"那几条就白算了。
  // ⚠ 只记坏的那几句、**不另立判据**：`段` 空着就是这一批干净。
  function 记账(o) {
    if (!o) return;
    if (!账) 账 = { 批: 0, 命令: 0, 段: [] };
    账.批++;
    账.命令 += (o.命令 || 0);
    if (o.段 && o.段.length) {
      for (var i = 0; i < o.段.length; i++) 账.段.push(String(o.段[i]));
    }
  }

  // 翻篇：老师又发了一句 = 上一轮到此为止。结算它，然后开新的一轮。
  function 翻篇() {
    if (本轮坏) 连败++; else 连败 = 0;
    本轮坏 = false;
    上轮账 = 账;      // ★ 上一轮到此为止，它攒的板子账就此定稿（见文件上面那段）
    账 = null;
  }

  // 给探针看的。正式代码不用它（正式代码只走 note）。
  function 数() { return 连败; }

  // 取走上一轮那份账，**只给一次**。由 api.js 的 buildSystem 调。
  //   ★ 取走就清掉，不留在那儿发第二遍：这是一句"此刻的实情"，不是一条规矩。
  //     清不掉的话，老师后面每一轮都会读到同一段陈年旧账，而提示词里
  //     **字面存在一句已经过时的事实**，比不写坏得多（它会照着那句话去改一张早改好的图）。
  function 取账() { var o = 上轮账; 上轮账 = null; return o; }

  // 换工位、整场重来之类的地方清一下。★ 清空**不**在这儿，理由见括号②。
  //   ⚠ 账一起清：换了工位就是换了一块板／一件事，上一个工位的旧账贴过去只会误导。
  function 归零() { 连败 = 0; 本轮坏 = false; 账 = null; 上轮账 = null; }

  // ------------------------------------------------------------
  //  要追加的那一段。空串 = 这一轮不用追加（绝大多数时候都是空串）。
  //
  //  ★ 位置就是它的全部本事：api.js 里必须**接在所有附注的最后**（含 PROMPT_SAY_TAIL）。
  //    小模型只认真读到的东西，挪到前面等于没做 —— 这一条是实测过的，
  //    见备忘《要模型每轮都做同一件事·写在提示词最末尾》。
  // ------------------------------------------------------------
  function note() {
    if (连败 >= 保护线) {
      return [
        '# 收敛保护：这一轮是最后一次修补',
        '',
        '连着 ' + 连败 + ' 轮没画成了。**这不是某一行的毛病，是这张图的结构想错了。**',
        '',
        '这一轮只许做一件事：**从头重画一版** —— 把这张图该由哪几个点、哪几条线、',
        '哪几个圆派生出来，重新推一遍先后关系，然后整张画出来。',
        '画完自己看状态条：还有「画板没认」，就**停手**，直接跟老师说卡在哪一步、',
        '要他改哪个条件才画得成。',
        '',
        '**不许再接着上一版挪一点改一点。** 改颜色、改粗细、放慢动画都不算修好 ——',
        '样式命令一个对象都造不出来，画面上少的那条线不会因为它冒出来。'
      ].join('\n');
    }
    if (连败 >= 提醒线) {
      return [
        '# 停一下：连着 ' + 连败 + ' 轮没画成了',
        '',
        '别再在当前这张图上挪一点、改一点。**回到老师最初那句话**，把这张图该由',
        '哪几个点、哪几条线派生出来重新想一遍，然后**整张重画**。',
        '',
        '接着上一版的坐标往下修，是修不出来的 —— 已经数了两轮了。'
      ].join('\n');
    }
    return '';
  }

  SR.converge = { 记坏: 记坏, 翻篇: 翻篇, 归零: 归零, note: note, 数: 数,
                   记账: 记账, 取账: 取账 };
})();
