// ★ 它跟另外五个的**输入形态不同**：别的都是一句话进去、一段回答出来；
//   这一格进来的是一张表（智学网导出的成绩表），老师从这一格拿走的是
//   **一张按得分率排好序的表 + 先讲哪三道**。
//
// ★ 三条实测经验落在下面这几处，别删：
//   ① 示范那一段（"完整的回复长这样"）**必须留**——删了小模型就自己编格式。
//   ② 要模型每轮都做的事，写在**最末尾**，挪了位置就掉（见 [[prompt-must-do-at-tail]]）。
//   ③ 这是一颗小模型，一次只服从得了一件事——规矩只留三条，别加第四条。
//
// ★★ 规矩二是这一格**最容易犯的错**，必须写死：老师那张表上是整份卷子
//   （模拟稿里是 40 道），而**只有口袋里那几道是他自己出的题**。不写这条，
//   模型会把整张表从低到高排出来——那个数看着像学情，其实混进了别人的题。
//   模拟稿里那句话说得很准：「口袋里有题号，成绩才排得出名次」。
//
// ★★ 2026-10-04 补的两个洞（六工位摸底跑出来的，孔老师那句"各种功能都要做检测"）。
//   这一格原来的**每一条规矩、连示范在内，都建立在"表已经交上来了"这个前提上**，
//   于是老师只打一句话进来的时候，它没得可依，就自己造了一张**空表格**：
//   实测原文是「整张表 **[假设总题数]** 道题…第 **[题号]** 题 **[得分率]%**」。
//   查过源码，`[题号]`／`[得分率]` 这些方括号**提示词里一个字都没有**——
//   是它现编的。这种空位比"答不上来"严重得多：老师会当成真数据去讲课。
//   两处病根，各下一味药：
//   ① **规矩一原本只管"口袋空着"，没管"表还没来"**——这是两回事，补齐成 (1)(2) 两档，
//      仍然收在**同一条**规矩里（文件顶上那句"规矩只留三条"是实测出来的，
//      不许为这个再开第四条）。方括号那一条并进规矩二，不单独立条。
//   ② 示范里那行 `（老师交来一张表，口袋里是第 12–17 题）` 是**舞台指示**，
//      小模型把它当成台词抄了。改法不是删掉它（删了就没有"当时什么情形"这个信息），
//      是**把它并进小标题**——标题不会被当成一句要说的话。
//      同一处还加了"只有真正拿到那张表才照这个样子回"。
//   ③ 末尾那条"每次回话第一句先说一共几道题"是**无条件**的，正是它逼出了那个假数。
//      改成**有表才说**，没表就说没表。
//
// ⚠ 写提示词时**引号一律用全角「」**：这里面每一行都是一个 JS 字符串，
//   半角 " 会把整段代码拆坏（这一版第一稿就栽在这儿）。
